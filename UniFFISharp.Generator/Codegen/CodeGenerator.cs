    private static void GenerateLibraryClass(CSharpCodeBuilder cb, ComponentInterface ci, string crateNorm, string dllName)
    {
        using (cb.Block("internal static partial class _UniFFILib"))
        {
            cb.AppendLine("#if (IOS || MACCATALYST || TVOS) && UNIFFI_STATIC_LINK");
            cb.AppendLine("    private const string DllName = \"__Internal\";");
            cb.AppendLine("#else");
            cb.AppendLine($"    private const string DllName = \"{dllName}\";");
            cb.AppendLine("#endif");
            cb.AppendLine();

            // Alloc / Free helpers
            using (cb.Block("public static RustBuffer Alloc(int size)"))
            {
                using (cb.Block("return UniffiHelpers.RustCall((ref UniffiRustCallStatus status) =>"))
                {
                    cb.AppendLine($"var buf = ffi_{crateNorm}_rustbuffer_alloc((ulong)size, ref status);");
                    cb.AppendLine("if (buf.data == IntPtr.Zero) throw new AllocationException($\"RustBuffer.Alloc returned null data pointer (size={size})\");");
                    cb.AppendLine("return buf;");
                }
                cb.AppendLine(");");
            }
            cb.AppendLine();

            using (cb.Block("public static void Free(RustBuffer buffer)"))
            {
                using (cb.Block("UniffiHelpers.RustCall((ref UniffiRustCallStatus status) =>"))
                {
                    cb.AppendLine($"ffi_{crateNorm}_rustbuffer_free(buffer, ref status);");
                }
                cb.AppendLine(");");
            }
            cb.AppendLine();

            // Static Constructor with verification & callback registration
            using (cb.Block("static _UniFFILib()"))
            {
                cb.AppendLine("#if NETCOREAPP3_0_OR_GREATER || NET5_0_OR_GREATER");
                using (cb.Block("try"))
                {
                    using (cb.Block("NativeLibrary.SetDllImportResolver(typeof(_UniFFILib).Assembly, (libraryName, assembly, searchPath) =>"))
                    {
                        using (cb.Block($"if (libraryName == DllName || libraryName == \"{dllName}\" || libraryName == \"{dllName}.dll\" || libraryName == \"__Internal\")"))
                        {
                            cb.AppendLine("IntPtr mainHandle = NativeLibrary.GetMainProgramHandle();");
                            using (cb.Block($"if (NativeLibrary.TryGetExport(mainHandle, \"ffi_{crateNorm}_uniffi_contract_version\", out _))"))
                            {
                                cb.AppendLine("return mainHandle;");
                            }
                            using (cb.Block($"if (NativeLibrary.TryLoad(\"{dllName}\", assembly, searchPath, out IntPtr handle))"))
                            {
                                cb.AppendLine("return handle;");
                            }
                            using (cb.Block($"if (NativeLibrary.TryLoad(\"{dllName}.dll\", assembly, searchPath, out IntPtr handleDll))"))
                            {
                                cb.AppendLine("return handleDll;");
                            }
                        }
                        cb.AppendLine("return IntPtr.Zero;");
                    }
                    cb.AppendLine(");");
                }
                using (cb.Block("catch (InvalidOperationException)"))
                {
                    cb.AppendLine("// Resolver already registered for this assembly");
                }
                cb.AppendLine("#endif");
                cb.AppendLine();
                cb.AppendLine("uniffiCheckContractApiVersion();");
                cb.AppendLine("uniffiCheckApiChecksums();");

                foreach (var cbi in ci.CallbackInterfaces)
                {
                    cb.AppendLine($"RegisterCallback_{TypeHelper.ToPascalCase(cbi.Name)}();");
                }
            }
            cb.AppendLine();

            // Contract Version Check
            using (cb.Block("static void uniffiCheckContractApiVersion()"))
            {
                using (cb.Block("try"))
                {
                    cb.AppendLine($"_ = ffi_{crateNorm}_uniffi_contract_version();");
                }
                using (cb.Block("catch (EntryPointNotFoundException)"))
                {
                    cb.AppendLine("// Scaffolding version symbol omitted; ignored.");
                }
            }
            cb.AppendLine();

            // Checksums Check
            using (cb.Block("static void uniffiCheckApiChecksums()"))
            {
                foreach (var fn in ci.Functions)
                {
                    if (fn.Checksum.HasValue)
                    {
                        using (cb.Block("try"))
                        {
                            string checkFn = $"uniffi_{crateNorm}_checksum_func_{fn.Name.ToLowerInvariant()}";
                            cb.AppendLine($"var checksum = {checkFn}();");
                            cb.AppendLine($"if (checksum != {fn.Checksum.Value}) throw new UniffiContractChecksumException($\"Checksum mismatch for {fn.Name}: expected {fn.Checksum.Value}, got {{checksum}}\");");
                        }
                        using (cb.Block("catch (EntryPointNotFoundException)"))
                        {
                            cb.AppendLine("// Checksum symbol omitted; ignored.");
                        }
                    }
                }
            }
            cb.AppendLine();

            // RustBuffer FFI imports
            cb.AppendLine($"[DllImport(DllName, EntryPoint = \"ffi_{crateNorm}_rustbuffer_alloc\", CallingConvention = CallingConvention.Cdecl)]");
            cb.AppendLine($"public static extern RustBuffer ffi_{crateNorm}_rustbuffer_alloc(ulong size, ref UniffiRustCallStatus status);");
            cb.AppendLine();
            cb.AppendLine($"[DllImport(DllName, EntryPoint = \"ffi_{crateNorm}_rustbuffer_free\", CallingConvention = CallingConvention.Cdecl)]");
            cb.AppendLine($"public static extern void ffi_{crateNorm}_rustbuffer_free(RustBuffer buffer, ref UniffiRustCallStatus status);");
            cb.AppendLine();
            cb.AppendLine($"[DllImport(DllName, EntryPoint = \"ffi_{crateNorm}_uniffi_contract_version\", CallingConvention = CallingConvention.Cdecl)]");
            cb.AppendLine($"public static extern uint ffi_{crateNorm}_uniffi_contract_version();");
            cb.AppendLine();

            // Rust Future FFI imports (for async functions)
            var declaredFutureSuffixes = new HashSet<string>(StringComparer.Ordinal);
            void DeclareFutureFns(UniFFIType? returnType)
            {
                string suffix = TypeHelper.FutureSuffix(returnType);
                if (!declaredFutureSuffixes.Add(suffix)) return;

                string completeFfi = TypeHelper.FutureCompleteFfiType(returnType);

                cb.AppendLine($"[DllImport(DllName, EntryPoint = \"ffi_{crateNorm}_rust_future_poll_{suffix}\", CallingConvention = CallingConvention.Cdecl)]");
                cb.AppendLine($"public static extern void ffi_{crateNorm}_rust_future_poll_{suffix}(ulong handle, IntPtr callback, ulong data);");
                cb.AppendLine();
                cb.AppendLine($"[DllImport(DllName, EntryPoint = \"ffi_{crateNorm}_rust_future_complete_{suffix}\", CallingConvention = CallingConvention.Cdecl)]");
                cb.AppendLine($"public static extern {completeFfi} ffi_{crateNorm}_rust_future_complete_{suffix}(ulong handle, ref UniffiRustCallStatus status);");
                cb.AppendLine();
                cb.AppendLine($"[DllImport(DllName, EntryPoint = \"ffi_{crateNorm}_rust_future_free_{suffix}\", CallingConvention = CallingConvention.Cdecl)]");
                cb.AppendLine($"public static extern void ffi_{crateNorm}_rust_future_free_{suffix}(ulong handle);");
                cb.AppendLine();
            }

            foreach (var fn in ci.Functions)
            {
                if (fn.IsAsync) DeclareFutureFns(fn.ReturnType);
            }
            foreach (var obj in ci.Objects)
            {
                foreach (var ctor in obj.Constructors) if (ctor.IsAsync) DeclareFutureFns(null);
                foreach (var m in obj.Methods) if (m.IsAsync) DeclareFutureFns(m.ReturnType);
            }

            // Function Checksums & Function Declarations
            foreach (var fn in ci.Functions)
            {
                string fnLower = fn.Name.ToLowerInvariant();
                if (fn.Checksum.HasValue)
                {
                    cb.AppendLine($"[DllImport(DllName, EntryPoint = \"uniffi_{crateNorm}_checksum_func_{fnLower}\", CallingConvention = CallingConvention.Cdecl)]");
                    cb.AppendLine($"public static extern ushort uniffi_{crateNorm}_checksum_func_{fnLower}();");
                    cb.AppendLine();
                }

                var ffiParams = new List<string>();
                foreach (var param in fn.Inputs)
                {
                    ffiParams.Add($"{TypeHelper.ToFfiType(param.Type)} {TypeHelper.ToCamelCase(param.Name)}");
                }

                if (fn.IsAsync)
                {
                    // Async returns ulong (future handle) and takes NO status param
                    string paramList = string.Join(", ", ffiParams);
                    cb.AppendLine($"[DllImport(DllName, EntryPoint = \"uniffi_{crateNorm}_fn_func_{fnLower}\", CallingConvention = CallingConvention.Cdecl)]");
                    cb.AppendLine($"public static extern ulong uniffi_{crateNorm}_fn_func_{fnLower}({paramList});");
                }
                else
                {
                    string retFfi = fn.ReturnType != null ? TypeHelper.ToFfiType(fn.ReturnType) : "void";
                    ffiParams.Add("ref UniffiRustCallStatus status");
                    string paramList = string.Join(", ", ffiParams);
                    cb.AppendLine($"[DllImport(DllName, EntryPoint = \"uniffi_{crateNorm}_fn_func_{fnLower}\", CallingConvention = CallingConvention.Cdecl)]");
                    cb.AppendLine($"public static extern {retFfi} uniffi_{crateNorm}_fn_func_{fnLower}({paramList});");
                }
                cb.AppendLine();
            }

            // Object constructors & methods
            foreach (var obj in ci.Objects)
            {
                string objLower = obj.Name.ToLowerInvariant();

                cb.AppendLine($"[DllImport(DllName, EntryPoint = \"uniffi_{crateNorm}_fn_clone_{objLower}\", CallingConvention = CallingConvention.Cdecl)]");
                cb.AppendLine($"public static extern IntPtr uniffi_{crateNorm}_fn_clone_{objLower}(IntPtr ptr, ref UniffiRustCallStatus status);");
                cb.AppendLine();
                cb.AppendLine($"[DllImport(DllName, EntryPoint = \"uniffi_{crateNorm}_fn_free_{objLower}\", CallingConvention = CallingConvention.Cdecl)]");
                cb.AppendLine($"public static extern void uniffi_{crateNorm}_fn_free_{objLower}(IntPtr ptr, ref UniffiRustCallStatus status);");
                cb.AppendLine();

                foreach (var ctor in obj.Constructors)
                {
                    string ctorLower = ctor.Name.ToLowerInvariant();
                    var ffiParams = new List<string>();
                    foreach (var param in ctor.Inputs)
                    {
                        ffiParams.Add($"{TypeHelper.ToFfiType(param.Type)} {TypeHelper.ToCamelCase(param.Name)}");
                    }

                    if (ctor.IsAsync)
                    {
                        cb.AppendLine($"[DllImport(DllName, EntryPoint = \"uniffi_{crateNorm}_fn_constructor_{objLower}_{ctorLower}\", CallingConvention = CallingConvention.Cdecl)]");
                        cb.AppendLine($"public static extern ulong uniffi_{crateNorm}_fn_constructor_{objLower}_{ctorLower}({string.Join(", ", ffiParams)});");
                    }
                    else
                    {
                        ffiParams.Add("ref UniffiRustCallStatus status");
                        cb.AppendLine($"[DllImport(DllName, EntryPoint = \"uniffi_{crateNorm}_fn_constructor_{objLower}_{ctorLower}\", CallingConvention = CallingConvention.Cdecl)]");
                        cb.AppendLine($"public static extern IntPtr uniffi_{crateNorm}_fn_constructor_{objLower}_{ctorLower}({string.Join(", ", ffiParams)});");
                    }
                    cb.AppendLine();
                }

                foreach (var m in obj.Methods)
                {
                    string mLower = m.Name.ToLowerInvariant();
                    var ffiParams = new List<string> { "IntPtr ptr" };
                    foreach (var param in m.Inputs)
                    {
                        ffiParams.Add($"{TypeHelper.ToFfiType(param.Type)} {TypeHelper.ToCamelCase(param.Name)}");
                    }

                    if (m.IsAsync)
                    {
                        cb.AppendLine($"[DllImport(DllName, EntryPoint = \"uniffi_{crateNorm}_fn_method_{objLower}_{mLower}\", CallingConvention = CallingConvention.Cdecl)]");
                        cb.AppendLine($"public static extern ulong uniffi_{crateNorm}_fn_method_{objLower}_{mLower}({string.Join(", ", ffiParams)});");
                    }
                    else
                    {
                        string retFfi = m.ReturnType != null ? TypeHelper.ToFfiType(m.ReturnType) : "void";
                        ffiParams.Add("ref UniffiRustCallStatus status");
                        cb.AppendLine($"[DllImport(DllName, EntryPoint = \"uniffi_{crateNorm}_fn_method_{objLower}_{mLower}\", CallingConvention = CallingConvention.Cdecl)]");
                        cb.AppendLine($"public static extern {retFfi} uniffi_{crateNorm}_fn_method_{objLower}_{mLower}({string.Join(", ", ffiParams)});");
                    }
                    cb.AppendLine();
                }
            }

            // Callback Interfaces VTable & P/Invokes
            foreach (var cbi in ci.CallbackInterfaces)
            {
                GenerateCallbackLibrarySupport(cb, cbi, crateNorm);
            }
        }
        cb.AppendLine();
    }

    private static void GenerateCallbackLibrarySupport(CSharpCodeBuilder cb, CallbackInterfaceMetadata cbi, string crateNorm)
    {
        string cbiName = TypeHelper.ToPascalCase(cbi.Name);
        string cbiLower = cbi.Name.ToLowerInvariant();

        // 1. VTable Struct (UniFFI 0.32 layout: uniffi_free, uniffi_clone first, then method pointers)
        using (cb.Block($"[StructLayout(LayoutKind.Sequential)] public struct UniFfiVTable{cbiName}"))
        {
            cb.AppendLine("public IntPtr uniffiFree;");
            cb.AppendLine("public IntPtr uniffiClone;");
            for (int i = 0; i < cbi.Methods.Count; i++)
            {
                cb.AppendLine($"public IntPtr m{i};");
            }
        }
        cb.AppendLine();

        // 2. Init callback P/Invoke
        cb.AppendLine($"[DllImport(DllName, EntryPoint = \"uniffi_{crateNorm}_fn_init_callback_vtable_{cbiLower}\", CallingConvention = CallingConvention.Cdecl)]");
        cb.AppendLine($"public static extern void uniffi_{crateNorm}_fn_init_callback_vtable_{cbiLower}(IntPtr vtable);");
        cb.AppendLine();

        // 3. Delegate declarations
        for (int i = 0; i < cbi.Methods.Count; i++)
        {
            var m = cbi.Methods[i];
            var ffiParams = new List<string> { "ulong uniffiHandle" };
            foreach (var p in m.Inputs)
            {
                ffiParams.Add($"{TypeHelper.ToFfiType(p.Type)} {TypeHelper.ToCamelCase(p.Name)}");
            }
            if (m.IsAsync)
            {
                ffiParams.Add("IntPtr uniffiFutureCallback");
                ffiParams.Add("ulong uniffiCallbackData");
                ffiParams.Add("IntPtr uniffiOutReturn");
            }
            else
            {
                ffiParams.Add("IntPtr uniffiOutReturn");
                ffiParams.Add("ref UniffiRustCallStatus callStatus");
            }

            cb.AppendLine($"[UnmanagedFunctionPointer(CallingConvention.Cdecl)]");
            cb.AppendLine($"public delegate void CallbackDelegate_{cbiName}_{i}({string.Join(", ", ffiParams)});");
            cb.AppendLine();

            if (m.IsAsync)
            {
                string? ffiRet = m.ReturnType != null ? TypeHelper.ToFfiType(m.ReturnType) : null;
                string resultStruct = $"ForeignFutureStruct_{cbiName}_{i}";
                string delegateType = $"ForeignFutureCompleteDelegate_{cbiName}_{i}";

                cb.AppendLine("[StructLayout(LayoutKind.Sequential)]");
                using (cb.Block($"public struct {resultStruct}"))
                {
                    if (ffiRet != null)
                    {
                        cb.AppendLine($"public {ffiRet} returnValue;");
                    }
                    cb.AppendLine("public UniffiRustCallStatus callStatus;");
                }
                cb.AppendLine();
                cb.AppendLine("[UnmanagedFunctionPointer(CallingConvention.Cdecl)]");
                cb.AppendLine($"public delegate void {delegateType}(ulong callbackData, {resultStruct} result);");
                cb.AppendLine();
            }
        }

        // 4. Delegate instances and Pinned GCHandle
        cb.AppendLine($"private static GCHandle? _vtablePin_{cbiName};");
        cb.AppendLine($"private static UniffiCallbackInterfaceFree? _freeDelegate_{cbiName};");
        cb.AppendLine($"private static UniffiCallbackInterfaceClone? _cloneDelegate_{cbiName};");
        for (int i = 0; i < cbi.Methods.Count; i++)
        {
            cb.AppendLine($"private static CallbackDelegate_{cbiName}_{i}? _methodDelegate_{cbiName}_{i};");
        }
        cb.AppendLine();

        // 5. Method implementations
        for (int i = 0; i < cbi.Methods.Count; i++)
        {
            var m = cbi.Methods[i];
            var ffiParams = new List<string> { "ulong uniffiHandle" };
            foreach (var p in m.Inputs)
            {
                ffiParams.Add($"{TypeHelper.ToFfiType(p.Type)} {TypeHelper.ToCamelCase(p.Name)}");
            }

            var callArgs = new List<string>();
            foreach (var p in m.Inputs)
            {
                if (TypeHelper.IsFfiPrimitive(p.Type))
                {
                    callArgs.Add(TypeHelper.ToCamelCase(p.Name));
                }
                else
                {
                    callArgs.Add($"{TypeHelper.ConverterInstance(p.Type)}.Lift({TypeHelper.ToCamelCase(p.Name)})");
                }
            }

            string methodName = TypeHelper.ToPascalCase(m.Name);
            if (m.IsAsync && !methodName.EndsWith("Async")) methodName += "Async";

            if (m.IsAsync)
            {
                ffiParams.Add("IntPtr uniffiFutureCallback");
                ffiParams.Add("ulong uniffiCallbackData");
                ffiParams.Add("IntPtr uniffiOutReturn");

                string? ffiRet = m.ReturnType != null ? TypeHelper.ToFfiType(m.ReturnType) : null;
                string resultStruct = $"ForeignFutureStruct_{cbiName}_{i}";
                string delegateType = $"ForeignFutureCompleteDelegate_{cbiName}_{i}";

                using (cb.Block($"private static void CallbackMethod_{cbiName}_{i}({string.Join(", ", ffiParams)})"))
                {
                    cb.AppendLine("var futureHandle = new UniffiForeignFutureHandle();");
                    cb.AppendLine("var foreignHandle = _UniFFIAsync.ForeignFuturesMap.Insert(futureHandle);");
                    using (cb.Block("unsafe"))
                    {
                        cb.AppendLine("var pDropped = (ForeignFutureDroppedCallbackStruct*)uniffiOutReturn.ToPointer();");
                        cb.AppendLine("pDropped->handle = foreignHandle;");
                        cb.AppendLine("pDropped->free = _UniFFIAsync.DroppedCallbackPointer;");
                    }
                    cb.AppendLine();

                    using (cb.Block($"if (!FfiConverterType{cbiName}.handleMap.TryGet(uniffiHandle, out var obj) || obj == null)"))
                    {
                        cb.AppendLine($"var earlyRet = new {resultStruct}();");
                        cb.AppendLine("earlyRet.callStatus.code = UniffiCallbackResponseStatus.UNEXPECTED_ERROR;");
                        using (cb.Block("try"))
                        {
                            cb.AppendLine($"earlyRet.callStatus.error_buf = FfiConverterString.INSTANCE.Lower($\"No callback found for handle {{uniffiHandle}}\");");
                        }
                        using (cb.Block("catch")) { }
                        cb.AppendLine($"var earlyCb = Marshal.GetDelegateForFunctionPointer<{delegateType}>(uniffiFutureCallback);");
                        cb.AppendLine("futureHandle.InvokeCallbackOnce(() => earlyCb(uniffiCallbackData, earlyRet));");
                        cb.AppendLine("futureHandle.Dispose();");
                        cb.AppendLine("return;");
                    }
                    cb.AppendLine();

                    string callExpr = $"obj.{methodName}({string.Join(", ", callArgs)})";

                    using (cb.Block("Task.Run(async () =>", ", futureHandle.Cts.Token);"))
                    {
                        cb.AppendLine($"var ret = new {resultStruct}();");
                        using (cb.Block("try"))
                        {
                            using (cb.Block("try"))
                            {
                                if (m.ReturnType == null)
                                {
                                    cb.AppendLine("#if NET6_0_OR_GREATER");
                                    cb.AppendLine($"await {callExpr}.WaitAsync(futureHandle.Cts.Token);");
                                    cb.AppendLine("#else");
                                    cb.AppendLine($"await {callExpr};");
                                    cb.AppendLine("#endif");
                                }
                                else
                                {
                                    cb.AppendLine("#if NET6_0_OR_GREATER");
                                    cb.AppendLine($"var result = await {callExpr}.WaitAsync(futureHandle.Cts.Token);");
                                    cb.AppendLine("#else");
                                    cb.AppendLine($"var result = await {callExpr};");
                                    cb.AppendLine("#endif");
                                    string loweredExpr = TypeHelper.IsFfiPrimitive(m.ReturnType) ? "result" : $"{TypeHelper.ConverterInstance(m.ReturnType)}.Lower(result)";
                                    cb.AppendLine($"ret.returnValue = {loweredExpr};");
                                }
                                cb.AppendLine("ret.callStatus.code = UniffiCallbackResponseStatus.SUCCESS;");
                            }
                            if (m.Throws != null)
                            {
                                using (cb.Block($"catch ({TypeHelper.ToCSharpType(m.Throws)} ex)"))
                                {
                                    using (cb.Block("try"))
                                    {
                                        cb.AppendLine("ret.callStatus.code = UniffiCallbackResponseStatus.ERROR;");
                                        cb.AppendLine($"ret.callStatus.error_buf = {TypeHelper.ConverterInstance(m.Throws)}.Lower(ex);");
                                    }
                                    using (cb.Block("catch"))
                                    {
                                        cb.AppendLine("ret.callStatus.code = UniffiCallbackResponseStatus.UNEXPECTED_ERROR;");
                                    }
                                }
                            }
                            using (cb.Block("catch (OperationCanceledException) when (futureHandle.Cts.IsCancellationRequested)"))
                            {
                                cb.AppendLine("ret.callStatus.code = UniffiCallbackResponseStatus.UNEXPECTED_ERROR;");
                                using (cb.Block("try"))
                                {
                                    cb.AppendLine("ret.callStatus.error_buf = FfiConverterString.INSTANCE.Lower(\"Future cancelled\");");
                                }
                                using (cb.Block("catch")) { }
                            }
                            using (cb.Block("catch (Exception ex)"))
                            {
                                cb.AppendLine("ret.callStatus.code = UniffiCallbackResponseStatus.UNEXPECTED_ERROR;");
                                using (cb.Block("try"))
                                {
                                    cb.AppendLine("ret.callStatus.error_buf = FfiConverterString.INSTANCE.Lower(ex.Message);");
                                }
                                using (cb.Block("catch")) { }
                            }
                            cb.AppendLine();
                            cb.AppendLine($"var cb = Marshal.GetDelegateForFunctionPointer<{delegateType}>(uniffiFutureCallback);");
                            cb.AppendLine("futureHandle.InvokeCallbackOnce(() => cb(uniffiCallbackData, ret));");
                        }
                        using (cb.Block("finally"))
                        {
                            cb.AppendLine("futureHandle.Dispose();");
                        }
                    }
                }
                cb.AppendLine();
            }
            else
            {
                ffiParams.Add("IntPtr uniffiOutReturn");
                ffiParams.Add("ref UniffiRustCallStatus callStatus");

                using (cb.Block($"private static void CallbackMethod_{cbiName}_{i}({string.Join(", ", ffiParams)})"))
                {
                    using (cb.Block($"if (!FfiConverterType{cbiName}.handleMap.TryGet(uniffiHandle, out var obj) || obj == null)"))
                    {
                        cb.AppendLine("callStatus.code = UniffiCallbackResponseStatus.UNEXPECTED_ERROR;");
                        cb.AppendLine($"callStatus.error_buf = FfiConverterString.INSTANCE.Lower($\"No callback found for handle {{uniffiHandle}}\");");
                        cb.AppendLine("return;");
                    }
                    using (cb.Block("try"))
                    {
                        string callExpr = $"obj.{methodName}({string.Join(", ", callArgs)})";

                        if (m.ReturnType == null)
                        {
                            cb.AppendLine($"{callExpr};");
                        }
                        else
                        {
                            cb.AppendLine($"var res = {callExpr};");
                            string ffiRet = TypeHelper.ToFfiType(m.ReturnType);
                            string loweredExpr = TypeHelper.IsFfiPrimitive(m.ReturnType) ? "res" : $"{TypeHelper.ConverterInstance(m.ReturnType)}.Lower(res)";
                            using (cb.Block("unsafe"))
                            {
                                cb.AppendLine($"*({ffiRet}*)uniffiOutReturn.ToPointer() = {loweredExpr};");
                            }
                        }
                        cb.AppendLine("callStatus.code = UniffiCallbackResponseStatus.SUCCESS;");
                    }
                    if (m.Throws != null)
                    {
                        using (cb.Block($"catch ({TypeHelper.ToCSharpType(m.Throws)} ex)"))
                        {
                            cb.AppendLine("callStatus.code = UniffiCallbackResponseStatus.ERROR;");
                            cb.AppendLine($"callStatus.error_buf = {TypeHelper.ConverterInstance(m.Throws)}.Lower(ex);");
                        }
                    }
                    using (cb.Block("catch (Exception ex)"))
                    {
                        cb.AppendLine("callStatus.code = UniffiCallbackResponseStatus.UNEXPECTED_ERROR;");
                        cb.AppendLine("callStatus.error_buf = FfiConverterString.INSTANCE.Lower(ex.Message);");
                    }
                }
                cb.AppendLine();
            }
        }

        // 6. Registration method
        using (cb.Block($"public static void RegisterCallback_{cbiName}()"))
        {
            using (cb.Block($"if (_vtablePin_{cbiName}.HasValue)"))
            {
                cb.AppendLine("return;");
            }
            using (cb.Block("try"))
            {
                cb.AppendLine($"_freeDelegate_{cbiName} = (handle) => FfiConverterType{cbiName}.handleMap.Remove(handle);");
                cb.AppendLine($"_cloneDelegate_{cbiName} = (handle) => FfiConverterType{cbiName}.handleMap.TryGet(handle, out var o) && o != null ? FfiConverterType{cbiName}.handleMap.Insert(o) : 0;");
                for (int i = 0; i < cbi.Methods.Count; i++)
                {
                    cb.AppendLine($"_methodDelegate_{cbiName}_{i} = CallbackMethod_{cbiName}_{i};");
                }

                using (cb.Block($"var vtable = new UniFfiVTable{cbiName}", ";"))
                {
                    cb.AppendLine($"uniffiFree = Marshal.GetFunctionPointerForDelegate(_freeDelegate_{cbiName}),");
                    cb.AppendLine($"uniffiClone = Marshal.GetFunctionPointerForDelegate(_cloneDelegate_{cbiName}),");
                    for (int i = 0; i < cbi.Methods.Count; i++)
                    {
                        cb.AppendLine($"m{i} = Marshal.GetFunctionPointerForDelegate(_methodDelegate_{cbiName}_{i}),");
                    }
                }

                cb.AppendLine($"_vtablePin_{cbiName} = GCHandle.Alloc(vtable, GCHandleType.Pinned);");
                cb.AppendLine($"uniffi_{crateNorm}_fn_init_callback_vtable_{cbiLower}(_vtablePin_{cbiName}.Value.AddrOfPinnedObject());");
            }
            using (cb.Block("catch (EntryPointNotFoundException)"))
            {
                cb.AppendLine($"// Callback interface {cbiName} init symbol omitted; ignored.");
            }
        }
        cb.AppendLine();
    }

    private static void GenerateCallbackInterface(CSharpCodeBuilder cb, CallbackInterfaceMetadata cbi, string crateNorm)
    {
        string cbiName = TypeHelper.ToPascalCase(cbi.Name);
        string ifaceName = "I" + cbiName;

        // Interface definition
        AppendDocComment(cb, cbi.Docstring);
        using (cb.Block($"public interface {ifaceName}"))
        {
            foreach (var m in cbi.Methods)
            {
                AppendDocComment(cb, m.Docstring);
                foreach (var p in m.Inputs)
                {
                    AppendParamComment(cb, TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name)), p.Docstring);
                }

                string retType = m.ReturnType != null ? TypeHelper.ToCSharpType(m.ReturnType) : "void";
                if (m.IsAsync)
                {
                    retType = m.ReturnType != null ? $"Task<{retType}>" : "Task";
                }
                var paramDecls = new List<string>();
                foreach (var p in m.Inputs)
                {
                    string def = p.DefaultValue != null ? $" = {p.DefaultValue}" : "";
                    paramDecls.Add($"{TypeHelper.ToCSharpType(p.Type)} {TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name))}{def}");
                }
                string methodName = TypeHelper.ToPascalCase(m.Name);
                if (m.IsAsync && !methodName.EndsWith("Async")) methodName += "Async";
                cb.AppendLine($"{retType} {methodName}({string.Join(", ", paramDecls)});");
            }
        }
        cb.AppendLine();

        // Converter
        using (cb.Block($"public sealed class FfiConverterType{cbiName} : FfiConverter<{ifaceName}, ulong>"))
        {
            cb.AppendLine($"public static readonly FfiConverterType{cbiName} INSTANCE = new();");
            cb.AppendLine($"public static readonly ConcurrentHandleMap<{ifaceName}> handleMap = new();");
            cb.AppendLine();
            using (cb.Block($"static FfiConverterType{cbiName}()"))
            {
                cb.AppendLine($"_UniFFILib.RegisterCallback_{cbiName}();");
            }
            cb.AppendLine();
            cb.AppendLine($"public override ulong Lower({ifaceName} value) => handleMap.Insert(value);");
            cb.AppendLine($"public override {ifaceName} Lift(ulong value) => handleMap.Get(value);");
            cb.AppendLine($"public override int AllocationSize({ifaceName} value) => 8;");
            cb.AppendLine($"public override void Write({ifaceName} value, BigEndianStream stream) => stream.WriteUInt64(Lower(value));");
            cb.AppendLine($"public override {ifaceName} Read(BigEndianStream stream) => Lift(stream.ReadUInt64());");
        }
        cb.AppendLine();
    }

    private static void GenerateRecord(CSharpCodeBuilder cb, RecordMetadata rec)
    {
        string recordName = TypeHelper.ToPascalCase(rec.Name);

        // Record Declaration
        AppendDocComment(cb, rec.Docstring);
        var orderedFields = rec.Fields.OrderBy(f => f.DefaultValue != null ? 1 : 0).ToList();
        foreach (var field in orderedFields)
        {
            AppendParamComment(cb, TypeHelper.EscapeIdentifier(TypeHelper.ToPascalCase(field.Name)), field.Docstring);
        }

        var paramDecls = new List<string>();
        foreach (var field in orderedFields)
        {
            string def = field.DefaultValue != null ? $" = {field.DefaultValue}" : "";
            paramDecls.Add($"{TypeHelper.ToCSharpType(field.Type)} {TypeHelper.EscapeIdentifier(TypeHelper.ToPascalCase(field.Name))}{def}");
        }
        cb.AppendLine($"public record {recordName}({string.Join(", ", paramDecls)});");
        cb.AppendLine();

        // Record Converter
        using (cb.Block($"public sealed class FfiConverterType{recordName} : FfiConverterRustBuffer<{recordName}>"))
        {
            cb.AppendLine($"public static readonly FfiConverterType{recordName} INSTANCE = new();");
            cb.AppendLine();
            cb.AppendLine("public override RustBuffer Alloc(int size) => _UniFFILib.Alloc(size);");
            cb.AppendLine("public override void Free(RustBuffer buffer) => _UniFFILib.Free(buffer);");
            cb.AppendLine();

            using (cb.Block($"public override int AllocationSize({recordName} value)"))
            {
                cb.AppendLine("int size = 0;");
                foreach (var field in rec.Fields)
                {
                    string prop = $"value.{TypeHelper.EscapeIdentifier(TypeHelper.ToPascalCase(field.Name))}";
                    cb.AppendLine($"size += {TypeHelper.ConverterInstance(field.Type)}.AllocationSize({prop});");
                }
                cb.AppendLine("return size;");
            }
            cb.AppendLine();

            using (cb.Block($"public override void Write({recordName} value, BigEndianStream stream)"))
            {
                foreach (var field in rec.Fields)
                {
                    string prop = $"value.{TypeHelper.EscapeIdentifier(TypeHelper.ToPascalCase(field.Name))}";
                    cb.AppendLine($"{TypeHelper.ConverterInstance(field.Type)}.Write({prop}, stream);");
                }
            }
            cb.AppendLine();

            using (cb.Block($"public override {recordName} Read(BigEndianStream stream)"))
            {
                foreach (var field in rec.Fields)
                {
                    cb.AppendLine($"var _{TypeHelper.ToCamelCase(field.Name).TrimStart('@')} = {TypeHelper.ConverterInstance(field.Type)}.Read(stream);");
                }
                cb.AppendLine($"return new {recordName}(");
                cb.Indent();
                for (int i = 0; i < orderedFields.Count; i++)
                {
                    var f = orderedFields[i];
                    string comma = (i < orderedFields.Count - 1) ? "," : "";
                    cb.AppendLine($"{TypeHelper.EscapeIdentifier(TypeHelper.ToPascalCase(f.Name))}: _{TypeHelper.ToCamelCase(f.Name).TrimStart('@')}{comma}");
                }
                cb.Unindent();
                cb.AppendLine(");");
            }
        }
        cb.AppendLine();
    }

    private static void GenerateEnum(CSharpCodeBuilder cb, EnumMetadata enm)
    {
        string enumName = TypeHelper.ToPascalCase(enm.Name);
        AppendDocComment(cb, enm.Docstring);

        if (enm.Shape == EnumShape.Enum && enm.Variants.All(v => v.Fields.Count == 0))
        {
            // Simple flat enum
            using (cb.Block($"public enum {enumName}"))
            {
                for (int i = 0; i < enm.Variants.Count; i++)
                {
                    var v = enm.Variants[i];
                    string comma = (i < enm.Variants.Count - 1) ? "," : "";
                    AppendDocComment(cb, v.Docstring);
                    cb.AppendLine($"{TypeHelper.ToPascalCase(v.Name)} = {i + 1}{comma}");
                }
            }
            cb.AppendLine();

            using (cb.Block($"public sealed class FfiConverterType{enumName} : FfiConverterRustBuffer<{enumName}>"))
            {
                cb.AppendLine($"public static readonly FfiConverterType{enumName} INSTANCE = new();");
                cb.AppendLine();
                cb.AppendLine("public override RustBuffer Alloc(int size) => _UniFFILib.Alloc(size);");
                cb.AppendLine("public override void Free(RustBuffer buffer) => _UniFFILib.Free(buffer);");
                cb.AppendLine($"public override int AllocationSize({enumName} value) => 4;");
                cb.AppendLine($"public override void Write({enumName} value, BigEndianStream stream) => stream.WriteInt32((int)value);");
                using (cb.Block($"public override {enumName} Read(BigEndianStream stream)"))
                {
                    cb.AppendLine("int tag = stream.ReadInt32();");
                    cb.AppendLine($"return ({enumName})tag;");
                }
            }
            cb.AppendLine();
        }
        else if (enm.Shape == EnumShape.ErrorFlat)
        {
            // Flat error enum
            using (cb.Block($"public class {enumName} : UniffiException"))
            {
                cb.AppendLine($"public {enumName}(string message) : base(message) {{ }}");
                cb.AppendLine();
                foreach (var v in enm.Variants)
                {
                    string vName = TypeHelper.ToPascalCase(v.Name);
                    AppendDocComment(cb, v.Docstring);
                    cb.AppendLine($"public class {vName} : {enumName} {{ public {vName}(string message) : base(message) {{ }} }}");
                }
            }
            cb.AppendLine();

            using (cb.Block($"public sealed class FfiConverterType{enumName} : FfiConverterRustBuffer<{enumName}>, CallStatusErrorHandler<{enumName}>"))
            {
                cb.AppendLine($"public static readonly FfiConverterType{enumName} INSTANCE = new();");
                cb.AppendLine();
                cb.AppendLine("public override RustBuffer Alloc(int size) => _UniFFILib.Alloc(size);");
                cb.AppendLine("public override void Free(RustBuffer buffer) => _UniFFILib.Free(buffer);");
                cb.AppendLine();
                using (cb.Block($"public override int AllocationSize({enumName} value)"))
                {
                    cb.AppendLine("return 4 + FfiConverterString.INSTANCE.AllocationSize(value.Message);");
                }
                cb.AppendLine();
                using (cb.Block($"public override void Write({enumName} value, BigEndianStream stream)"))
                {
                    using (cb.Block("switch (value)"))
                    {
                        for (int i = 0; i < enm.Variants.Count; i++)
                        {
                            var v = enm.Variants[i];
                            string vName = TypeHelper.ToPascalCase(v.Name);
                            using (cb.Block($"case {enumName}.{vName}:"))
                            {
                                cb.AppendLine($"stream.WriteInt32({i + 1});");
                                cb.AppendLine("FfiConverterString.INSTANCE.Write(value.Message, stream);");
                                cb.AppendLine("break;");
                            }
                        }
                        using (cb.Block("default:"))
                        {
                            cb.AppendLine($"throw new InternalException($\"Unknown error variant: {{value}}\");");
                        }
                    }
                }
                cb.AppendLine();
                using (cb.Block($"public override {enumName} Read(BigEndianStream stream)"))
                {
                    cb.AppendLine("int tag = stream.ReadInt32();");
                    cb.AppendLine("string msg = FfiConverterString.INSTANCE.Read(stream);");
                    using (cb.Block("return tag switch", ";"))
                    {
                        for (int i = 0; i < enm.Variants.Count; i++)
                        {
                            var v = enm.Variants[i];
                            string vName = TypeHelper.ToPascalCase(v.Name);
                            cb.AppendLine($"{i + 1} => new {enumName}.{vName}(msg),");
                        }
                        cb.AppendLine($"_ => throw new InternalException($\"Unknown error tag: {{tag}}\")");
                    }
                }
            }
            cb.AppendLine();
        }
        else if (enm.Shape == EnumShape.ErrorComplex)
        {
            // Complex error enum
            using (cb.Block($"public abstract class {enumName} : UniffiException"))
            {
                cb.AppendLine($"private {enumName}(string message = \"\") : base(message) {{ }}");
                cb.AppendLine();
                foreach (var v in enm.Variants)
                {
                    AppendDocComment(cb, v.Docstring);
                    string vName = TypeHelper.ToPascalCase(v.Name);
                    if (v.Fields.Count == 0)
                    {
                        cb.AppendLine($"public sealed class {vName} : {enumName} {{ public {vName}() : base(\"{vName}\") {{ }} }}");
                    }
                    else
                    {
                        var orderedFields = v.Fields.OrderBy(f => f.DefaultValue != null ? 1 : 0).ToList();
                        var paramDecls = new List<string>();
                        foreach (var f in orderedFields)
                        {
                            string def = f.DefaultValue != null ? $" = {f.DefaultValue}" : "";
                            paramDecls.Add($"{TypeHelper.ToCSharpType(f.Type)} {TypeHelper.EscapeIdentifier(TypeHelper.ToPascalCase(f.Name))}{def}");
                        }
                        using (cb.Block($"public sealed class {vName} : {enumName}"))
                        {
                            foreach (var f in v.Fields)
                            {
                                cb.AppendLine($"public {TypeHelper.ToCSharpType(f.Type)} {TypeHelper.EscapeIdentifier(TypeHelper.ToPascalCase(f.Name))} {{ get; }}");
                            }
                            cb.AppendLine();
                            using (cb.Block($"public {vName}({string.Join(", ", paramDecls)}) : base(\"{vName}\")"))
                            {
                                foreach (var f in v.Fields)
                                {
                                    cb.AppendLine($"this.{TypeHelper.EscapeIdentifier(TypeHelper.ToPascalCase(f.Name))} = {TypeHelper.EscapeIdentifier(TypeHelper.ToPascalCase(f.Name))};");
                                }
                            }
                        }
                    }
                }
            }
            cb.AppendLine();

            using (cb.Block($"public sealed class FfiConverterType{enumName} : FfiConverterRustBuffer<{enumName}>, CallStatusErrorHandler<{enumName}>"))
            {
                cb.AppendLine($"public static readonly FfiConverterType{enumName} INSTANCE = new();");
                cb.AppendLine();
                cb.AppendLine("public override RustBuffer Alloc(int size) => _UniFFILib.Alloc(size);");
                cb.AppendLine("public override void Free(RustBuffer buffer) => _UniFFILib.Free(buffer);");
                cb.AppendLine();
                using (cb.Block($"public override int AllocationSize({enumName} value)"))
                {
                    cb.AppendLine("int size = 4;");
                    using (cb.Block("switch (value)"))
                    {
                        for (int i = 0; i < enm.Variants.Count; i++)
                        {
                            var v = enm.Variants[i];
                            string vName = TypeHelper.ToPascalCase(v.Name);
                            using (cb.Block($"case {enumName}.{vName} v:"))
                            {
                                foreach (var f in v.Fields)
                                {
                                    cb.AppendLine($"size += {TypeHelper.ConverterInstance(f.Type)}.AllocationSize(v.{TypeHelper.ToPascalCase(f.Name)});");
                                }
                                cb.AppendLine("break;");
                            }
                        }
                    }
                    cb.AppendLine("return size;");
                }
                cb.AppendLine();
                using (cb.Block($"public override void Write({enumName} value, BigEndianStream stream)"))
                {
                    using (cb.Block("switch (value)"))
                    {
                        for (int i = 0; i < enm.Variants.Count; i++)
                        {
                            var v = enm.Variants[i];
                            string vName = TypeHelper.ToPascalCase(v.Name);
                            if (v.Fields.Count == 0)
                            {
                                using (cb.Block($"case {enumName}.{vName}:"))
                                {
                                    cb.AppendLine($"stream.WriteInt32({i + 1});");
                                    cb.AppendLine("break;");
                                }
                            }
                            else
                            {
                                using (cb.Block($"case {enumName}.{vName} v:"))
                                {
                                    cb.AppendLine($"stream.WriteInt32({i + 1});");
                                    foreach (var f in v.Fields)
                                    {
                                        cb.AppendLine($"{TypeHelper.ConverterInstance(f.Type)}.Write(v.{TypeHelper.ToPascalCase(f.Name)}, stream);");
                                    }
                                    cb.AppendLine("break;");
                                }
                            }
                        }
                    }
                }
                cb.AppendLine();
                using (cb.Block($"public override {enumName} Read(BigEndianStream stream)"))
                {
                    cb.AppendLine("int tag = stream.ReadInt32();");
                    using (cb.Block("switch (tag)"))
                    {
                        for (int i = 0; i < enm.Variants.Count; i++)
                        {
                            var v = enm.Variants[i];
                            string vName = TypeHelper.ToPascalCase(v.Name);
                            using (cb.Block($"case {i + 1}:"))
                            {
                                if (v.Fields.Count == 0)
                                {
                                    cb.AppendLine($"return new {enumName}.{vName}();");
                                }
                                else
                                {
                                    var argReads = new List<string>();
                                    foreach (var f in v.Fields)
                                    {
                                        argReads.Add($"{TypeHelper.ConverterInstance(f.Type)}.Read(stream)");
                                    }
                                    cb.AppendLine($"return new {enumName}.{vName}({string.Join(", ", argReads)});");
                                }
                            }
                        }
                        using (cb.Block("default:"))
                        {
                            cb.AppendLine($"throw new InternalException($\"Unknown error tag: {{tag}}\");");
                        }
                    }
                }
            }
            cb.AppendLine();
        }
        else
        {
            // Tagged union record enum
            using (cb.Block($"public abstract record {enumName}"))
            {
                cb.AppendLine($"private {enumName}() {{ }}");
                cb.AppendLine();
                foreach (var v in enm.Variants)
                {
                    AppendDocComment(cb, v.Docstring);
                    string vName = TypeHelper.ToPascalCase(v.Name);
                    if (v.Fields.Count == 0)
                    {
                        cb.AppendLine($"public sealed record {vName}() : {enumName};");
                    }
                    else
                    {
                        var orderedFields = v.Fields.OrderBy(f => f.DefaultValue != null ? 1 : 0).ToList();
                        var paramDecls = new List<string>();
                        foreach (var f in orderedFields)
                        {
                            string def = f.DefaultValue != null ? $" = {f.DefaultValue}" : "";
                            paramDecls.Add($"{TypeHelper.ToCSharpType(f.Type)} {TypeHelper.EscapeIdentifier(TypeHelper.ToPascalCase(f.Name))}{def}");
                        }
                        cb.AppendLine($"public sealed record {vName}({string.Join(", ", paramDecls)}) : {enumName};");
                    }
                }
            }
            cb.AppendLine();

            using (cb.Block($"public sealed class FfiConverterType{enumName} : FfiConverterRustBuffer<{enumName}>"))
            {
                cb.AppendLine($"public static readonly FfiConverterType{enumName} INSTANCE = new();");
                cb.AppendLine();
                cb.AppendLine("public override RustBuffer Alloc(int size) => _UniFFILib.Alloc(size);");
                cb.AppendLine("public override void Free(RustBuffer buffer) => _UniFFILib.Free(buffer);");
                cb.AppendLine();
                using (cb.Block($"public override int AllocationSize({enumName} value)"))
                {
                    cb.AppendLine("int size = 4;");
                    using (cb.Block("switch (value)"))
                    {
                        for (int i = 0; i < enm.Variants.Count; i++)
                        {
                            var v = enm.Variants[i];
                            string vName = TypeHelper.ToPascalCase(v.Name);
                            using (cb.Block($"case {enumName}.{vName} v:"))
                            {
                                foreach (var f in v.Fields)
                                {
                                    cb.AppendLine($"size += {TypeHelper.ConverterInstance(f.Type)}.AllocationSize(v.{TypeHelper.ToPascalCase(f.Name)});");
                                }
                                cb.AppendLine("break;");
                            }
                        }
                    }
                    cb.AppendLine("return size;");
                }
                cb.AppendLine();
                using (cb.Block($"public override void Write({enumName} value, BigEndianStream stream)"))
                {
                    using (cb.Block("switch (value)"))
                    {
                        for (int i = 0; i < enm.Variants.Count; i++)
                        {
                            var v = enm.Variants[i];
                            string vName = TypeHelper.ToPascalCase(v.Name);
                            if (v.Fields.Count == 0)
                            {
                                using (cb.Block($"case {enumName}.{vName}:"))
                                {
                                    cb.AppendLine($"stream.WriteInt32({i + 1});");
                                    cb.AppendLine("break;");
                                }
                            }
                            else
                            {
                                using (cb.Block($"case {enumName}.{vName} v:"))
                                {
                                    cb.AppendLine($"stream.WriteInt32({i + 1});");
                                    foreach (var f in v.Fields)
                                    {
                                        cb.AppendLine($"{TypeHelper.ConverterInstance(f.Type)}.Write(v.{TypeHelper.ToPascalCase(f.Name)}, stream);");
                                    }
                                    cb.AppendLine("break;");
                                }
                            }
                        }
                    }
                }
                cb.AppendLine();
                using (cb.Block($"public override {enumName} Read(BigEndianStream stream)"))
                {
                    cb.AppendLine("int tag = stream.ReadInt32();");
                    using (cb.Block("switch (tag)"))
                    {
                        for (int i = 0; i < enm.Variants.Count; i++)
                        {
                            var v = enm.Variants[i];
                            string vName = TypeHelper.ToPascalCase(v.Name);
                            using (cb.Block($"case {i + 1}:"))
                            {
                                if (v.Fields.Count == 0)
                                {
                                    cb.AppendLine($"return new {enumName}.{vName}();");
                                }
                                else
                                {
                                    var orderedFields = v.Fields.OrderBy(f => f.DefaultValue != null ? 1 : 0).ToList();
                                    foreach (var f in v.Fields)
                                    {
                                        cb.AppendLine($"var _{TypeHelper.ToCamelCase(f.Name).TrimStart('@')} = {TypeHelper.ConverterInstance(f.Type)}.Read(stream);");
                                    }
                                    var namedArgs = orderedFields.Select(f => $"{TypeHelper.EscapeIdentifier(TypeHelper.ToPascalCase(f.Name))}: _{TypeHelper.ToCamelCase(f.Name).TrimStart('@')}");
                                    cb.AppendLine($"return new {enumName}.{vName}({string.Join(", ", namedArgs)});");
                                }
                            }
                        }
                        using (cb.Block("default:"))
                        {
                            cb.AppendLine($"throw new InternalException($\"Unknown tag: {{tag}}\");");
                        }
                    }
                }
            }
            cb.AppendLine();
        }
    }

    private static void GenerateObject(CSharpCodeBuilder cb, ObjectMetadata obj, string crateNorm)
    {
        string objName = TypeHelper.ToPascalCase(obj.Name);
        string ifaceName = "I" + objName;
        string objLower = obj.Name.ToLowerInvariant();

        // Interface
        AppendDocComment(cb, obj.Docstring);
        using (cb.Block($"public interface {ifaceName} : IDisposable"))
        {
            foreach (var m in obj.Methods)
            {
                AppendDocComment(cb, m.Docstring);
                foreach (var p in m.Inputs)
                {
                    AppendParamComment(cb, TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name)), p.Docstring);
                }
                string retType = m.ReturnType != null ? TypeHelper.ToCSharpType(m.ReturnType) : "void";
                if (m.IsAsync)
                {
                    retType = m.ReturnType != null ? $"Task<{retType}>" : "Task";
                }
                var paramDecls = new List<string>();
                foreach (var p in m.Inputs)
                {
                    string def = p.DefaultValue != null ? $" = {p.DefaultValue}" : "";
                    paramDecls.Add($"{TypeHelper.ToCSharpType(p.Type)} {TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name))}{def}");
                }
                string methodName = TypeHelper.ToPascalCase(m.Name);
                if (m.IsAsync && !methodName.EndsWith("Async")) methodName += "Async";
                cb.AppendLine($"{retType} {methodName}({string.Join(", ", paramDecls)});");
            }
        }
        cb.AppendLine();

        // Class
        AppendDocComment(cb, obj.Docstring);
        using (cb.Block($"public class {objName} : {ifaceName}"))
        {
            cb.AppendLine("protected IntPtr _pointer;");
            cb.AppendLine("private int _wasDestroyed = 0;");
            cb.AppendLine("private long _callCounter = 1;");
            cb.AppendLine();
            cb.AppendLine($"internal {objName}(IntPtr pointer, bool isInternal)");
            using (cb.Block(""))
            {
                cb.AppendLine("_pointer = pointer;");
                cb.AppendLine("_callCounter = 1;");
                cb.AppendLine("_wasDestroyed = 0;");
            }
            cb.AppendLine($"internal static {objName} CreateInternal(IntPtr pointer) => new {objName}(pointer, true);");
            cb.AppendLine("internal IntPtr Pointer => _pointer;");
            cb.AppendLine();

            using (cb.Block("protected void FreeRustArcPtr()"))
            {
                using (cb.Block("UniffiHelpers.RustCall((ref UniffiRustCallStatus status) =>"))
                {
                    cb.AppendLine($"_UniFFILib.uniffi_{crateNorm}_fn_free_{objLower}(_pointer, ref status);");
                }
                cb.AppendLine(");");
            }
            cb.AppendLine();

            using (cb.Block("protected IntPtr CloneRustArcPtr()"))
            {
                cb.AppendLine($"if (_pointer == IntPtr.Zero) throw new ObjectDisposedException(nameof({objName}));");
                using (cb.Block("return UniffiHelpers.RustCall((ref UniffiRustCallStatus status) =>"))
                {
                    cb.AppendLine($"return _UniFFILib.uniffi_{crateNorm}_fn_clone_{objLower}(_pointer, ref status);");
                }
                cb.AppendLine(");");
            }
            cb.AppendLine();

            using (cb.Block("public void Destroy()"))
            {
                using (cb.Block("if (Interlocked.CompareExchange(ref _wasDestroyed, 1, 0) == 0)"))
                {
                    using (cb.Block("if (Interlocked.Decrement(ref _callCounter) == 0)"))
                    {
                        cb.AppendLine("FreeRustArcPtr();");
                    }
                }
            }
            cb.AppendLine();

            using (cb.Block("public void Dispose()"))
            {
                cb.AppendLine("Destroy();");
                cb.AppendLine("GC.SuppressFinalize(this);");
            }
            cb.AppendLine();

            using (cb.Block("private void IncrementCallCounter()"))
            {
                cb.AppendLine("long count;");
                using (cb.Block("do"))
                {
                    cb.AppendLine("count = Interlocked.Read(ref _callCounter);");
                    cb.AppendLine($"if (count == 0L) throw new ObjectDisposedException(nameof({objName}));");
                    cb.AppendLine($"if (count == long.MaxValue) throw new OverflowException(nameof({objName}));");
                }
                cb.AppendLine("while (Interlocked.CompareExchange(ref _callCounter, count + 1, count) != count);");
            }
            cb.AppendLine();

            using (cb.Block("private void DecrementCallCounter()"))
            {
                using (cb.Block("if (Interlocked.Decrement(ref _callCounter) == 0)"))
                {
                    cb.AppendLine("FreeRustArcPtr();");
                }
            }
            cb.AppendLine();

            using (cb.Block("internal void CallWithPointer(Action<IntPtr> action)"))
            {
                cb.AppendLine("IncrementCallCounter();");
                using (cb.Block("try"))
                {
                    cb.AppendLine("action(CloneRustArcPtr());");
                }
                using (cb.Block("finally"))
                {
                    cb.AppendLine("DecrementCallCounter();");
                }
            }
            cb.AppendLine();

            using (cb.Block("internal T CallWithPointer<T>(Func<IntPtr, T> func)"))
            {
                cb.AppendLine("IncrementCallCounter();");
                using (cb.Block("try"))
                {
                    cb.AppendLine("return func(CloneRustArcPtr());");
                }
                using (cb.Block("finally"))
                {
                    cb.AppendLine("DecrementCallCounter();");
                }
            }
            cb.AppendLine();

            cb.AppendLine("internal IntPtr ClonePointer() => CallWithPointer(thisPtr => thisPtr);");
            cb.AppendLine();

            // Constructors
            foreach (var ctor in obj.Constructors)
            {
                AppendDocComment(cb, ctor.Docstring);
                foreach (var p in ctor.Inputs)
                {
                    AppendParamComment(cb, TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name)), p.Docstring);
                }

                var paramDecls = new List<string>();
                var callArgs = new List<string>();
                foreach (var p in ctor.Inputs)
                {
                    string def = p.DefaultValue != null ? $" = {p.DefaultValue}" : "";
                    paramDecls.Add($"{TypeHelper.ToCSharpType(p.Type)} {TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name))}{def}");
                    if (TypeHelper.IsFfiPrimitive(p.Type))
                    {
                        callArgs.Add(TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name)));
                    }
                    else
                    {
                        callArgs.Add($"{TypeHelper.ConverterInstance(p.Type)}.Lower({TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name))})");
                    }
                }

                string ctorLower = ctor.Name.ToLowerInvariant();
                string ctorName = ctor.Name == "new" ? objName : TypeHelper.ToPascalCase(ctor.Name);
                string errorHandler = ctor.Throws != null ? TypeHelper.ConverterInstance(ctor.Throws) : "NullCallStatusErrorHandler.INSTANCE";

                if (ctor.IsAsync)
                {
                    string asyncCtorName = ctor.Name == "new" ? $"{objName}Async" : (ctorName.EndsWith("Async") ? ctorName : $"{ctorName}Async");
                    using (cb.Block($"public static async Task<{objName}> {asyncCtorName}({string.Join(", ", paramDecls)})"))
                    {
                        cb.AppendLine($"ulong futureHandle = _UniFFILib.uniffi_{crateNorm}_fn_constructor_{objLower}_{ctorLower}({string.Join(", ", callArgs)});");
                        cb.AppendLine($"var ptr = await _UniFFIAsync.UniffiRustCallAsync(");
                        cb.Indent();
                        cb.AppendLine("futureHandle,");
                        cb.AppendLine($"(f, cb, d) => _UniFFILib.ffi_{crateNorm}_rust_future_poll_u64(f, cb, d),");
                        cb.AppendLine($"(ulong f, ref UniffiRustCallStatus s) => (IntPtr)_UniFFILib.ffi_{crateNorm}_rust_future_complete_u64(f, ref s),");
                        cb.AppendLine($"(ulong f) => _UniFFILib.ffi_{crateNorm}_rust_future_free_u64(f),");
                        cb.AppendLine("res => res,");
                        cb.AppendLine($"{errorHandler}");
                        cb.Unindent();
                        cb.AppendLine(");");
                        cb.AppendLine($"return CreateInternal(ptr);");
                    }
                }
                else if (ctor.Name == "new")
                {
                    callArgs.Add("ref status");
                    using (cb.Block($"public {objName}({string.Join(", ", paramDecls)})"))
                    {
                        using (cb.Block($"_pointer = UniffiHelpers.RustCallWithError({errorHandler}, (ref UniffiRustCallStatus status) =>"))
                        {
                            cb.AppendLine($"return _UniFFILib.uniffi_{crateNorm}_fn_constructor_{objLower}_{ctorLower}({string.Join(", ", callArgs)});");
                        }
                        cb.AppendLine(");");
                    }
                }
                else
                {
                    callArgs.Add("ref status");
                    using (cb.Block($"public static {objName} {ctorName}({string.Join(", ", paramDecls)})"))
                    {
                        using (cb.Block($"var ptr = UniffiHelpers.RustCallWithError({errorHandler}, (ref UniffiRustCallStatus status) =>"))
                        {
                            cb.AppendLine($"return _UniFFILib.uniffi_{crateNorm}_fn_constructor_{objLower}_{ctorLower}({string.Join(", ", callArgs)});");
                        }
                        cb.AppendLine(");");
                        cb.AppendLine($"return CreateInternal(ptr);");
                    }
                }
                cb.AppendLine();
            }

            // Methods
            foreach (var m in obj.Methods)
            {
                AppendDocComment(cb, m.Docstring);
                foreach (var p in m.Inputs)
                {
                    AppendParamComment(cb, TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name)), p.Docstring);
                }

                string rawRetType = m.ReturnType != null ? TypeHelper.ToCSharpType(m.ReturnType) : "void";
                string retType = m.IsAsync ? (m.ReturnType != null ? $"Task<{rawRetType}>" : "Task") : rawRetType;
                var paramDecls = new List<string>();
                var callArgs = new List<string>();
                foreach (var p in m.Inputs)
                {
                    string def = p.DefaultValue != null ? $" = {p.DefaultValue}" : "";
                    paramDecls.Add($"{TypeHelper.ToCSharpType(p.Type)} {TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name))}{def}");
                    if (TypeHelper.IsFfiPrimitive(p.Type))
                    {
                        callArgs.Add(TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name)));
                    }
                    else
                    {
                        callArgs.Add($"{TypeHelper.ConverterInstance(p.Type)}.Lower({TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name))})");
                    }
                }

                string mLower = m.Name.ToLowerInvariant();
                string methodName = TypeHelper.ToPascalCase(m.Name);
                if (m.IsAsync && !methodName.EndsWith("Async")) methodName += "Async";
                string errorHandler = m.Throws != null ? TypeHelper.ConverterInstance(m.Throws) : "NullCallStatusErrorHandler.INSTANCE";
                string argsPrefix = callArgs.Count > 0 ? ", " + string.Join(", ", callArgs) : "";

                if (m.IsAsync)
                {
                    string suffix = TypeHelper.FutureSuffix(m.ReturnType);
                    using (cb.Block($"public async {retType} {methodName}({string.Join(", ", paramDecls)})"))
                    {
                        cb.AppendLine($"ulong futureHandle = CallWithPointer(thisPtr => _UniFFILib.uniffi_{crateNorm}_fn_method_{objLower}_{mLower}(thisPtr{argsPrefix}));");
                        if (m.ReturnType == null)
                        {
                            cb.AppendLine("await _UniFFIAsync.UniffiRustCallAsync(");
                            cb.Indent();
                            cb.AppendLine("futureHandle,");
                            cb.AppendLine($"(f, cb, d) => _UniFFILib.ffi_{crateNorm}_rust_future_poll_{suffix}(f, cb, d),");
                            cb.AppendLine($"(ulong f, ref UniffiRustCallStatus s) => _UniFFILib.ffi_{crateNorm}_rust_future_complete_{suffix}(f, ref s),");
                            cb.AppendLine($"(ulong f) => _UniFFILib.ffi_{crateNorm}_rust_future_free_{suffix}(f),");
                            cb.AppendLine($"{errorHandler}");
                            cb.Unindent();
                            cb.AppendLine(");");
                        }
                        else
                        {
                            cb.AppendLine("return await _UniFFIAsync.UniffiRustCallAsync(");
                            cb.Indent();
                            cb.AppendLine("futureHandle,");
                            cb.AppendLine($"(f, cb, d) => _UniFFILib.ffi_{crateNorm}_rust_future_poll_{suffix}(f, cb, d),");
                            cb.AppendLine($"(ulong f, ref UniffiRustCallStatus s) => _UniFFILib.ffi_{crateNorm}_rust_future_complete_{suffix}(f, ref s),");
                            cb.AppendLine($"(ulong f) => _UniFFILib.ffi_{crateNorm}_rust_future_free_{suffix}(f),");
                            string liftExpr = TypeHelper.IsFfiPrimitive(m.ReturnType) ? "res => res" : $"res => {TypeHelper.ConverterInstance(m.ReturnType)}.Lift(res)";
                            cb.AppendLine($"{liftExpr},");
                            cb.AppendLine($"{errorHandler}");
                            cb.Unindent();
                            cb.AppendLine(");");
                        }
                    }
                }
                else
                {
                    using (cb.Block($"public {retType} {methodName}({string.Join(", ", paramDecls)})"))
                    {
                        if (m.ReturnType == null)
                        {
                            using (cb.Block("CallWithPointer(thisPtr =>"))
                            {
                                using (cb.Block($"UniffiHelpers.RustCallWithError({errorHandler}, (ref UniffiRustCallStatus status) =>"))
                                {
                                    cb.AppendLine($"_UniFFILib.uniffi_{crateNorm}_fn_method_{objLower}_{mLower}(thisPtr{argsPrefix}, ref status);");
                                }
                                cb.AppendLine(");");
                            }
                            cb.AppendLine(");");
                        }
                        else
                        {
                            using (cb.Block("return CallWithPointer(thisPtr =>"))
                            {
                                using (cb.Block($"var res = UniffiHelpers.RustCallWithError({errorHandler}, (ref UniffiRustCallStatus status) =>"))
                                {
                                    cb.AppendLine($"return _UniFFILib.uniffi_{crateNorm}_fn_method_{objLower}_{mLower}(thisPtr{argsPrefix}, ref status);");
                                }
                                cb.AppendLine(");");
                                if (TypeHelper.IsFfiPrimitive(m.ReturnType))
                                {
                                    cb.AppendLine("return res;");
                                }
                                else
                                {
                                    cb.AppendLine($"return {TypeHelper.ConverterInstance(m.ReturnType)}.Lift(res);");
                                }
                            }
                            cb.AppendLine(");");
                        }
                    }
                }
                cb.AppendLine();
            }

            // Finalizer & IDisposable
            cb.AppendLine($"~{objName}() => Destroy();");
        }
        cb.AppendLine();

        // Object Converter
        using (cb.Block($"public sealed class FfiConverterType{objName} : FfiConverter<{objName}, IntPtr>"))
        {
            cb.AppendLine($"public static readonly FfiConverterType{objName} INSTANCE = new();");
            cb.AppendLine();
            cb.AppendLine($"public override IntPtr Lower({objName} value) => value != null ? value.ClonePointer() : IntPtr.Zero;");
            cb.AppendLine($"public override {objName} Lift(IntPtr value) => {objName}.CreateInternal(value);");
            cb.AppendLine($"public override int AllocationSize({objName} value) => 8;");
            cb.AppendLine($"public override void Write({objName} value, BigEndianStream stream) => stream.WriteInt64(Lower(value).ToInt64());");
            cb.AppendLine($"public override {objName} Read(BigEndianStream stream) => Lift((IntPtr)stream.ReadInt64());");
        }
        cb.AppendLine();
    }

    private static void GenerateTopLevelMethods(CSharpCodeBuilder cb, ComponentInterface ci, string ns, string crateNorm)
    {
        string className = $"{TypeHelper.ToPascalCase(crateNorm)}Methods";

        using (cb.Block($"public static class {className}"))
        {
            foreach (var fn in ci.Functions)
            {
                AppendDocComment(cb, fn.Docstring);
                foreach (var p in fn.Inputs)
                {
                    AppendParamComment(cb, TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name)), p.Docstring);
                }

                string rawRetType = fn.ReturnType != null ? TypeHelper.ToCSharpType(fn.ReturnType) : "void";
                string retType = fn.IsAsync ? (fn.ReturnType != null ? $"Task<{rawRetType}>" : "Task") : rawRetType;
                var paramDecls = new List<string>();
                var callArgs = new List<string>();

                foreach (var p in fn.Inputs)
                {
                    string def = p.DefaultValue != null ? $" = {p.DefaultValue}" : "";
                    paramDecls.Add($"{TypeHelper.ToCSharpType(p.Type)} {TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name))}{def}");
                    if (TypeHelper.IsFfiPrimitive(p.Type))
                    {
                        callArgs.Add(TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name)));
                    }
                    else
                    {
                        callArgs.Add($"{TypeHelper.ConverterInstance(p.Type)}.Lower({TypeHelper.EscapeIdentifier(TypeHelper.ToCamelCase(p.Name))})");
                    }
                }

                string fnLower = fn.Name.ToLowerInvariant();
                string methodName = TypeHelper.ToPascalCase(fn.Name);
                if (fn.IsAsync && !methodName.EndsWith("Async")) methodName += "Async";
                string errorHandler = fn.Throws != null ? TypeHelper.ConverterInstance(fn.Throws) : "NullCallStatusErrorHandler.INSTANCE";

                if (fn.IsAsync)
                {
                    string suffix = TypeHelper.FutureSuffix(fn.ReturnType);
                    using (cb.Block($"public static async {retType} {methodName}({string.Join(", ", paramDecls)})"))
                    {
                        cb.AppendLine($"ulong futureHandle = _UniFFILib.uniffi_{crateNorm}_fn_func_{fnLower}({string.Join(", ", callArgs)});");
                        if (fn.ReturnType == null)
                        {
                            cb.AppendLine("await _UniFFIAsync.UniffiRustCallAsync(");
                            cb.Indent();
                            cb.AppendLine("futureHandle,");
                            cb.AppendLine($"(f, cb, d) => _UniFFILib.ffi_{crateNorm}_rust_future_poll_{suffix}(f, cb, d),");
                            cb.AppendLine($"(ulong f, ref UniffiRustCallStatus s) => _UniFFILib.ffi_{crateNorm}_rust_future_complete_{suffix}(f, ref s),");
                            cb.AppendLine($"(ulong f) => _UniFFILib.ffi_{crateNorm}_rust_future_free_{suffix}(f),");
                            cb.AppendLine($"{errorHandler}");
                            cb.Unindent();
                            cb.AppendLine(");");
                        }
                        else
                        {
                            cb.AppendLine("return await _UniFFIAsync.UniffiRustCallAsync(");
                            cb.Indent();
                            cb.AppendLine("futureHandle,");
                            cb.AppendLine($"(f, cb, d) => _UniFFILib.ffi_{crateNorm}_rust_future_poll_{suffix}(f, cb, d),");
                            cb.AppendLine($"(ulong f, ref UniffiRustCallStatus s) => _UniFFILib.ffi_{crateNorm}_rust_future_complete_{suffix}(f, ref s),");
                            cb.AppendLine($"(ulong f) => _UniFFILib.ffi_{crateNorm}_rust_future_free_{suffix}(f),");
                            string liftExpr = TypeHelper.IsFfiPrimitive(fn.ReturnType) ? "res => res" : $"res => {TypeHelper.ConverterInstance(fn.ReturnType)}.Lift(res)";
                            cb.AppendLine($"{liftExpr},");
                            cb.AppendLine($"{errorHandler}");
                            cb.Unindent();
                            cb.AppendLine(");");
                        }
                    }
                }
                else
                {
                    callArgs.Add("ref status");
                    using (cb.Block($"public static {retType} {methodName}({string.Join(", ", paramDecls)})"))
                    {
                        if (fn.ReturnType == null)
                        {
                            using (cb.Block($"UniffiHelpers.RustCallWithError({errorHandler}, (ref UniffiRustCallStatus status) =>"))
                            {
                                cb.AppendLine($"_UniFFILib.uniffi_{crateNorm}_fn_func_{fnLower}({string.Join(", ", callArgs)});");
                            }
                            cb.AppendLine(");");
                        }
                        else
                        {
                            using (cb.Block($"var res = UniffiHelpers.RustCallWithError({errorHandler}, (ref UniffiRustCallStatus status) =>"))
                            {
                                cb.AppendLine($"return _UniFFILib.uniffi_{crateNorm}_fn_func_{fnLower}({string.Join(", ", callArgs)});");
                            }
                            cb.AppendLine(");");
                            if (TypeHelper.IsFfiPrimitive(fn.ReturnType))
                            {
                                cb.AppendLine("return res;");
                            }
                            else
                            {
                                cb.AppendLine($"return {TypeHelper.ConverterInstance(fn.ReturnType)}.Lift(res);");
                            }
                        }
                    }
                }
                cb.AppendLine();
            }
        }
    }
