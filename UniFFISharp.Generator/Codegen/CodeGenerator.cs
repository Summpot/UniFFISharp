public static class CodeGenerator
{
    public static string Generate(ComponentInterface ci, string dllFileName)
    {
        var cb = new CSharpCodeBuilder();
        string ns = string.IsNullOrEmpty(ci.Namespace) ? TypeHelper.ToPascalCase(ci.CrateName) : TypeHelper.ToPascalCase(ci.Namespace);
        string crateNorm = ci.CrateName.Replace('-', '_');
        string dllNameNoExt = Path.GetFileNameWithoutExtension(dllFileName);

        cb.AppendLine("// <auto-generated/>");
        cb.AppendLine("#nullable enable");
        cb.AppendLine("#pragma warning disable CS8625");
        cb.AppendLine("#pragma warning disable CS0105");
        cb.AppendLine();
        cb.AppendLine("using System;");
        cb.AppendLine("using System.Collections.Generic;");
        cb.AppendLine("using System.IO;");
        cb.AppendLine("using System.Runtime.InteropServices;");
        cb.AppendLine("using System.Text;");
        cb.AppendLine("using System.Threading;");
        cb.AppendLine("using System.Threading.Tasks;");
        cb.AppendLine("using UniFFISharp.Types;");
        cb.AppendLine("using UniFFISharp.Exceptions;");
        cb.AppendLine("using UniFFISharp.Streams;");
        cb.AppendLine("using UniFFISharp.Converters;");
        cb.AppendLine("using UniFFISharp.Helpers;");
        cb.AppendLine("using UniFFISharp.Collections;");
        cb.AppendLine("using UniFFISharp.Callbacks;");
        cb.AppendLine("using UniFFISharp.Async;");
        cb.AppendLine();
        cb.AppendLine($"namespace {ns};");
        cb.AppendLine();

        // 1. Built-in Converters (String, ByteArray, Timestamp, Duration)
        GenerateBuiltinConverters(cb);

        // 2. Composite Converters (Option, Sequence, Map, Set)
        var compositeTypes = FindCompositeTypes(ci);
        GenerateCompositeConverters(cb, compositeTypes);

        // 3. _UniFFILib P/Invoke class
        GenerateLibraryClass(cb, ci, crateNorm, dllNameNoExt);

        // 4. Records
        foreach (var rec in ci.Records)
        {
            GenerateRecord(cb, rec);
        }

        // 5. Enums
        foreach (var enm in ci.Enums)
        {
            GenerateEnum(cb, enm);
        }

        // 6. Objects / Interfaces
        foreach (var obj in ci.Objects)
        {
            GenerateObject(cb, obj, crateNorm);
        }

        // 7. Callback Interfaces
        foreach (var cbi in ci.CallbackInterfaces)
        {
            GenerateCallbackInterface(cb, cbi, crateNorm);
        }

        // 8. Top-level Functions
        GenerateTopLevelMethods(cb, ci, ns, crateNorm);

        return cb.ToString();
    }

    private static void AppendDocComment(CSharpCodeBuilder cb, string? docstring)
    {
        if (string.IsNullOrWhiteSpace(docstring)) return;
        cb.AppendLine("/// <summary>");
        var lines = docstring!.Trim().Split(new[] { "\r\n", "\r", "\n" }, StringSplitOptions.None);
        foreach (var line in lines)
        {
            cb.AppendLine($"/// {line.TrimEnd()}");
        }
        cb.AppendLine("/// </summary>");
    }

    private static void AppendParamComment(CSharpCodeBuilder cb, string paramName, string? docstring)
    {
        if (string.IsNullOrWhiteSpace(docstring)) return;
        var lines = docstring!.Trim().Split(new[] { "\r\n", "\r", "\n" }, StringSplitOptions.None);
        cb.AppendLine($"/// <param name=\"{paramName}\">");
        foreach (var line in lines)
        {
            cb.AppendLine($"/// {line.TrimEnd()}");
        }
        cb.AppendLine("/// </param>");
    }

    private static List<UniFFIType> FindCompositeTypes(ComponentInterface ci)
    {
        var list = new List<UniFFIType>();
        var seen = new HashSet<string>(StringComparer.Ordinal);

        void Visit(UniFFIType? type)
        {
            if (type == null) return;
            Visit(type.InnerType);
            Visit(type.KeyType);
            Visit(type.ValueType);

            if (type.Kind == TypeKind.Option || type.Kind == TypeKind.Sequence || type.Kind == TypeKind.Map || type.Kind == TypeKind.Set)
            {
                string id = TypeHelper.ConverterClassName(type);
                if (seen.Add(id))
                {
                    list.Add(type);
                }
            }
        }

        foreach (var fn in ci.Functions)
        {
            foreach (var p in fn.Inputs) Visit(p.Type);
            Visit(fn.ReturnType);
            Visit(fn.Throws);
        }
        foreach (var rec in ci.Records)
        {
            foreach (var f in rec.Fields) Visit(f.Type);
        }
        foreach (var enm in ci.Enums)
        {
            foreach (var v in enm.Variants)
            {
                foreach (var f in v.Fields) Visit(f.Type);
            }
        }
        foreach (var obj in ci.Objects)
        {
            foreach (var ctor in obj.Constructors)
            {
                foreach (var p in ctor.Inputs) Visit(p.Type);
                Visit(ctor.Throws);
            }
            foreach (var m in obj.Methods)
            {
                foreach (var p in m.Inputs) Visit(p.Type);
                Visit(m.ReturnType);
                Visit(m.Throws);
            }
        }
        foreach (var cbi in ci.CallbackInterfaces)
        {
            foreach (var m in cbi.Methods)
            {
                foreach (var p in m.Inputs) Visit(p.Type);
                Visit(m.ReturnType);
                Visit(m.Throws);
            }
        }

        return list;
    }

    private static void GenerateBuiltinConverters(CSharpCodeBuilder cb)
    {
        // String
        using (cb.Block("internal sealed class FfiConverterString : FfiConverter<string, RustBuffer>"))
        {
            cb.AppendLine("public static readonly FfiConverterString INSTANCE = new();");
            cb.AppendLine();
            using (cb.Block("public override string Lift(RustBuffer value)"))
            {
                using (cb.Block("try"))
                {
                    cb.AppendLine("var bytes = value.AsStream().ReadBytes(Convert.ToInt32(value.len));");
                    cb.AppendLine("return Encoding.UTF8.GetString(bytes);");
                }
                using (cb.Block("finally"))
                {
                    cb.AppendLine("_UniFFILib.Free(value);");
                }
            }
            cb.AppendLine();
            using (cb.Block("public override RustBuffer Lower(string value)"))
            {
                cb.AppendLine("value ??= string.Empty;");
                cb.AppendLine("byte[] bytes = Encoding.UTF8.GetBytes(value);");
                cb.AppendLine("var rbuf = _UniFFILib.Alloc(bytes.Length);");
                cb.AppendLine("rbuf.AsWriteableStream().WriteBytes(bytes);");
                cb.AppendLine("return rbuf;");
            }
            cb.AppendLine();
            cb.AppendLine("public override int AllocationSize(string value) => 4 + Encoding.UTF8.GetByteCount(value ?? string.Empty);");
            cb.AppendLine("public override void Write(string value, BigEndianStream stream) => stream.WriteString(value ?? string.Empty);");
            cb.AppendLine("public override string Read(BigEndianStream stream) => stream.ReadString();");
        }
        cb.AppendLine();

        // ByteArray
        using (cb.Block("internal sealed class FfiConverterByteArray : FfiConverterRustBuffer<byte[]>"))
        {
            cb.AppendLine("public static readonly FfiConverterByteArray INSTANCE = new();");
            cb.AppendLine();
            cb.AppendLine("public override RustBuffer Alloc(int size) => _UniFFILib.Alloc(size);");
            cb.AppendLine("public override void Free(RustBuffer buffer) => _UniFFILib.Free(buffer);");
            cb.AppendLine("public override int AllocationSize(byte[] value) => 4 + (value?.Length ?? 0);");
            using (cb.Block("public override void Write(byte[] value, BigEndianStream stream)"))
            {
                using (cb.Block("if (value == null)"))
                {
                    cb.AppendLine("stream.WriteInt32(0);");
                    cb.AppendLine("return;");
                }
                cb.AppendLine("stream.WriteInt32(value.Length);");
                cb.AppendLine("stream.WriteBytes(value);");
            }
            using (cb.Block("public override byte[] Read(BigEndianStream stream)"))
            {
                cb.AppendLine("int length = stream.ReadInt32();");
                cb.AppendLine("return stream.ReadBytes(length);");
            }
        }
        cb.AppendLine();

        // Timestamp
        using (cb.Block("internal sealed class FfiConverterTimestamp : FfiConverterRustBuffer<DateTimeOffset>"))
        {
            cb.AppendLine("public static readonly FfiConverterTimestamp INSTANCE = new();");
            cb.AppendLine();
            cb.AppendLine("public override RustBuffer Alloc(int size) => _UniFFILib.Alloc(size);");
            cb.AppendLine("public override void Free(RustBuffer buffer) => _UniFFILib.Free(buffer);");
            cb.AppendLine("public override int AllocationSize(DateTimeOffset value) => 12;");
            using (cb.Block("public override void Write(DateTimeOffset value, BigEndianStream stream)"))
            {
                cb.AppendLine("long seconds = value.ToUnixTimeSeconds();");
                cb.AppendLine("uint nanos = (uint)((value.Ticks % TimeSpan.TicksPerSecond) * 100);");
                cb.AppendLine("stream.WriteInt64(seconds);");
                cb.AppendLine("stream.WriteUInt32(nanos);");
            }
            using (cb.Block("public override DateTimeOffset Read(BigEndianStream stream)"))
            {
                cb.AppendLine("long seconds = stream.ReadInt64();");
                cb.AppendLine("uint nanos = stream.ReadUInt32();");
                cb.AppendLine("return DateTimeOffset.UnixEpoch.AddSeconds(seconds).AddTicks(nanos / 100);");
            }
        }
        cb.AppendLine();

        // Duration
        using (cb.Block("internal sealed class FfiConverterDuration : FfiConverterRustBuffer<TimeSpan>"))
        {
            cb.AppendLine("public static readonly FfiConverterDuration INSTANCE = new();");
            cb.AppendLine();
            cb.AppendLine("public override RustBuffer Alloc(int size) => _UniFFILib.Alloc(size);");
            cb.AppendLine("public override void Free(RustBuffer buffer) => _UniFFILib.Free(buffer);");
            cb.AppendLine("public override int AllocationSize(TimeSpan value) => 12;");
            using (cb.Block("public override void Write(TimeSpan value, BigEndianStream stream)"))
            {
                cb.AppendLine("ulong seconds = (ulong)(value.Ticks / TimeSpan.TicksPerSecond);");
                cb.AppendLine("uint nanos = (uint)((value.Ticks % TimeSpan.TicksPerSecond) * 100);");
                cb.AppendLine("stream.WriteUInt64(seconds);");
                cb.AppendLine("stream.WriteUInt32(nanos);");
            }
            using (cb.Block("public override TimeSpan Read(BigEndianStream stream)"))
            {
                cb.AppendLine("ulong seconds = stream.ReadUInt64();");
                cb.AppendLine("uint nanos = stream.ReadUInt32();");
                cb.AppendLine("long ticks = (long)seconds * TimeSpan.TicksPerSecond + (nanos / 100);");
                cb.AppendLine("return new TimeSpan(ticks);");
            }
        }
        cb.AppendLine();
    }

    private static void GenerateCompositeConverters(CSharpCodeBuilder cb, List<UniFFIType> compositeTypes)
    {
        foreach (var ty in compositeTypes)
        {
            if (ty.Kind == TypeKind.Option)
            {
                GenerateOptionalConverter(cb, ty);
            }
            else if (ty.Kind == TypeKind.Sequence)
            {
                GenerateSequenceConverter(cb, ty);
            }
            else if (ty.Kind == TypeKind.Map)
            {
                GenerateMapConverter(cb, ty);
            }
            else if (ty.Kind == TypeKind.Set)
            {
                GenerateSetConverter(cb, ty);
            }
        }
    }

    private static bool IsValueType(UniFFIType ty)
    {
        return ty.Kind switch
        {
            TypeKind.UInt8 or TypeKind.Int8 or TypeKind.UInt16 or TypeKind.Int16 or
            TypeKind.UInt32 or TypeKind.Int32 or TypeKind.UInt64 or TypeKind.Int64 or
            TypeKind.Float32 or TypeKind.Float64 or TypeKind.Boolean or
            TypeKind.Timestamp or TypeKind.Duration => true,
            _ => false
        };
    }

    private static void GenerateOptionalConverter(CSharpCodeBuilder cb, UniFFIType type)
    {
        var inner = type.InnerType!;
        string innerCsType = TypeHelper.ToCSharpType(inner);
        string innerConverter = TypeHelper.ConverterInstance(inner);
        string convName = TypeHelper.ConverterClassName(type);
        bool isVal = IsValueType(inner);

        using (cb.Block($"internal sealed class {convName} : FfiConverterRustBuffer<{innerCsType}?>"))
        {
            cb.AppendLine($"public static readonly {convName} INSTANCE = new();");
            cb.AppendLine();
            cb.AppendLine("public override RustBuffer Alloc(int size) => _UniFFILib.Alloc(size);");
            cb.AppendLine("public override void Free(RustBuffer buffer) => _UniFFILib.Free(buffer);");
            cb.AppendLine();
            using (cb.Block($"public override int AllocationSize({innerCsType}? value)"))
            {
                cb.AppendLine("if (value == null) return 1;");
                string valExpr = isVal ? "value.Value" : "value!";
                cb.AppendLine($"return 1 + {innerConverter}.AllocationSize({valExpr});");
            }
            cb.AppendLine();
            using (cb.Block($"public override void Write({innerCsType}? value, BigEndianStream stream)"))
            {
                using (cb.Block("if (value == null)"))
                {
                    cb.AppendLine("stream.WriteUInt8(0);");
                    cb.AppendLine("return;");
                }
                cb.AppendLine("stream.WriteUInt8(1);");
                string valExpr = isVal ? "value.Value" : "value!";
                cb.AppendLine($"{innerConverter}.Write({valExpr}, stream);");
            }
            cb.AppendLine();
            using (cb.Block($"public override {innerCsType}? Read(BigEndianStream stream)"))
            {
                using (cb.Block("if (stream.ReadUInt8() == 0)"))
                {
                    cb.AppendLine("return null;");
                }
                cb.AppendLine($"return {innerConverter}.Read(stream);");
            }
        }
        cb.AppendLine();
    }

    private static void GenerateSequenceConverter(CSharpCodeBuilder cb, UniFFIType type)
    {
        var inner = type.InnerType!;
        string innerCsType = TypeHelper.ToCSharpType(inner);
        string innerConverter = TypeHelper.ConverterInstance(inner);
        string convName = TypeHelper.ConverterClassName(type);

        using (cb.Block($"internal sealed class {convName} : FfiConverterRustBuffer<List<{innerCsType}>>"))
        {
            cb.AppendLine($"public static readonly {convName} INSTANCE = new();");
            cb.AppendLine();
            cb.AppendLine("public override RustBuffer Alloc(int size) => _UniFFILib.Alloc(size);");
            cb.AppendLine("public override void Free(RustBuffer buffer) => _UniFFILib.Free(buffer);");
            cb.AppendLine();
            using (cb.Block($"public override int AllocationSize(List<{innerCsType}> value)"))
            {
                cb.AppendLine("if (value == null) return 4;");
                cb.AppendLine("int size = 4;");
                using (cb.Block("foreach (var item in value)"))
                {
                    cb.AppendLine($"size += {innerConverter}.AllocationSize(item);");
                }
                cb.AppendLine("return size;");
            }
            cb.AppendLine();
            using (cb.Block($"public override void Write(List<{innerCsType}> value, BigEndianStream stream)"))
            {
                using (cb.Block("if (value == null)"))
                {
                    cb.AppendLine("stream.WriteInt32(0);");
                    cb.AppendLine("return;");
                }
                cb.AppendLine("stream.WriteInt32(value.Count);");
                using (cb.Block("foreach (var item in value)"))
                {
                    cb.AppendLine($"{innerConverter}.Write(item, stream);");
                }
            }
            cb.AppendLine();
            using (cb.Block($"public override List<{innerCsType}> Read(BigEndianStream stream)"))
            {
                cb.AppendLine("int count = stream.ReadInt32();");
                cb.AppendLine($"var list = new List<{innerCsType}>(count);");
                using (cb.Block("for (int i = 0; i < count; i++)"))
                {
                    cb.AppendLine($"list.Add({innerConverter}.Read(stream));");
                }
                cb.AppendLine("return list;");
            }
        }
        cb.AppendLine();
    }

    private static void GenerateMapConverter(CSharpCodeBuilder cb, UniFFIType type)
    {
        var key = type.KeyType!;
        var val = type.ValueType!;
        string keyCsType = TypeHelper.ToCSharpType(key);
        string valCsType = TypeHelper.ToCSharpType(val);
        string keyConverter = TypeHelper.ConverterInstance(key);
        string valConverter = TypeHelper.ConverterInstance(val);
        string convName = TypeHelper.ConverterClassName(type);

        using (cb.Block($"internal sealed class {convName} : FfiConverterRustBuffer<Dictionary<{keyCsType}, {valCsType}>>"))
        {
            cb.AppendLine($"public static readonly {convName} INSTANCE = new();");
            cb.AppendLine();
            cb.AppendLine("public override RustBuffer Alloc(int size) => _UniFFILib.Alloc(size);");
            cb.AppendLine("public override void Free(RustBuffer buffer) => _UniFFILib.Free(buffer);");
            cb.AppendLine();
            using (cb.Block($"public override int AllocationSize(Dictionary<{keyCsType}, {valCsType}> value)"))
            {
                cb.AppendLine("if (value == null) return 4;");
                cb.AppendLine("int size = 4;");
                using (cb.Block("foreach (var kv in value)"))
                {
                    cb.AppendLine($"size += {keyConverter}.AllocationSize(kv.Key) + {valConverter}.AllocationSize(kv.Value);");
                }
                cb.AppendLine("return size;");
            }
            cb.AppendLine();
            using (cb.Block($"public override void Write(Dictionary<{keyCsType}, {valCsType}> value, BigEndianStream stream)"))
            {
                using (cb.Block("if (value == null)"))
                {
                    cb.AppendLine("stream.WriteInt32(0);");
                    cb.AppendLine("return;");
                }
                cb.AppendLine("stream.WriteInt32(value.Count);");
                using (cb.Block("foreach (var kv in value)"))
                {
                    cb.AppendLine($"{keyConverter}.Write(kv.Key, stream);");
                    cb.AppendLine($"{valConverter}.Write(kv.Value, stream);");
                }
            }
            cb.AppendLine();
            using (cb.Block($"public override Dictionary<{keyCsType}, {valCsType}> Read(BigEndianStream stream)"))
            {
                cb.AppendLine("int count = stream.ReadInt32();");
                cb.AppendLine($"var dict = new Dictionary<{keyCsType}, {valCsType}>(count);");
                using (cb.Block("for (int i = 0; i < count; i++)"))
                {
                    cb.AppendLine($"var k = {keyConverter}.Read(stream);");
                    cb.AppendLine($"var v = {valConverter}.Read(stream);");
                    cb.AppendLine("dict[k] = v;");
                }
                cb.AppendLine("return dict;");
            }
        }
        cb.AppendLine();
    }

