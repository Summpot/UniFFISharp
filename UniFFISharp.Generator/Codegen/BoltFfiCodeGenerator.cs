    private static void EmitRecord(StringBuilder sb, BoltFfiRecordDecl record)
    {
        string recordName = record.Name.ToPascalCase();
        if (string.IsNullOrEmpty(recordName)) return;

        if (record.IsDirect)
        {
            sb.AppendLine("    [StructLayout(LayoutKind.Sequential)]");
            sb.AppendLine($"    public partial struct {recordName} : IEquatable<{recordName}>");
            sb.AppendLine("    {");

            foreach (var f in record.Fields)
            {
                string fName = ToPascal(f.Name);
                string fType = MapType(f.Type);
                sb.AppendLine($"        public {fType} {fName};");
            }

            // Constructor
            if (record.Fields.Count > 0)
            {
                sb.AppendLine();
                var paramList = new List<string>();
                foreach (var f in record.Fields)
                {
                    paramList.Add($"{MapType(f.Type)} {ToCamel(f.Name)}");
                }
                sb.AppendLine($"        public {recordName}({string.Join(", ", paramList)})");
                sb.AppendLine("        {");
                foreach (var f in record.Fields)
                {
                    sb.AppendLine($"            this.{ToPascal(f.Name)} = {ToCamel(f.Name)};");
                }
                sb.AppendLine("        }");
            }

            // Equality
            sb.AppendLine();
            sb.AppendLine($"        public bool Equals({recordName} other) =>");
            if (record.Fields.Count == 0)
            {
                sb.AppendLine("            true;");
            }
            else
            {
                var eqParts = new List<string>();
                foreach (var f in record.Fields)
                {
                    string fName = ToPascal(f.Name);
                    eqParts.Add($"EqualityComparer<{MapType(f.Type)}>.Default.Equals({fName}, other.{fName})");
                }
                sb.AppendLine($"            {string.Join(" &&\n            ", eqParts)};");
            }
            sb.AppendLine($"        public override bool Equals(object? obj) => obj is {recordName} other && Equals(other);");
            sb.AppendLine("        public override int GetHashCode()");
            sb.AppendLine("        {");
            if (record.Fields.Count == 0)
            {
                sb.AppendLine("            return 0;");
            }
            else
            {
                sb.AppendLine("            var hash = new HashCode();");
                foreach (var f in record.Fields)
                {
                    sb.AppendLine($"            hash.Add({ToPascal(f.Name)});");
                }
                sb.AppendLine("            return hash.ToHashCode();");
            }
            sb.AppendLine("        }");
            sb.AppendLine($"        public static bool operator ==({recordName} left, {recordName} right) => left.Equals(right);");
            sb.AppendLine($"        public static bool operator !=({recordName} left, {recordName} right) => !left.Equals(right);");

            sb.AppendLine("    }");
        }
        else
        {
            // Encoded record
            sb.AppendLine($"    public partial record struct {recordName}");
            sb.AppendLine("    {");
            foreach (var f in record.Fields)
            {
                string fName = ToPascal(f.Name);
                string fType = MapType(f.Type);
                sb.AppendLine($"        public {fType} {fName} {{ get; set; }}");
            }

            if (record.Fields.Count > 0)
            {
                sb.AppendLine();
                var paramList = new List<string>();
                foreach (var f in record.Fields)
                {
                    paramList.Add($"{MapType(f.Type)} {ToCamel(f.Name)}");
                }
                sb.AppendLine($"        public {recordName}({string.Join(", ", paramList)})");
                sb.AppendLine("        {");
                foreach (var f in record.Fields)
                {
                    sb.AppendLine($"            this.{ToPascal(f.Name)} = {ToCamel(f.Name)};");
                }
                sb.AppendLine("        }");
            }

            // Wire Decode
            sb.AppendLine();
            sb.AppendLine($"        internal static {recordName} Decode(WireReader reader) =>");
            sb.AppendLine($"            new {recordName}(");
            for (int i = 0; i < record.Fields.Count; i++)
            {
                string comma = (i == record.Fields.Count - 1) ? "" : ",";
                sb.AppendLine($"                {WireReadExpr(record.Fields[i].Type)}{comma}");
            }
            sb.AppendLine("            );");

            // Wire Encode
            sb.AppendLine();
            sb.AppendLine("        internal void Encode(WireWriter writer)");
            sb.AppendLine("        {");
            foreach (var f in record.Fields)
            {
                sb.AppendLine($"            {WireWriteStatement(f.Type, ToPascal(f.Name))};");
            }
            sb.AppendLine("        }");

            sb.AppendLine("    }");
        }
        sb.AppendLine();
    }

    private static void EmitEnum(StringBuilder sb, BoltFfiEnumDecl enumDecl)
    {
        string enumName = enumDecl.Name.ToPascalCase();
        if (string.IsNullOrEmpty(enumName)) return;

        bool isDataEnum = !enumDecl.IsCStyle || enumDecl.Variants.Any(v => v.PayloadFields.Count > 0);
        if (!isDataEnum)
        {
            sb.AppendLine($"    public enum {enumName}");
            sb.AppendLine("    {");
            long currentDisc = 0;
            foreach (var v in enumDecl.Variants)
            {
                long disc = v.Discriminant ?? currentDisc;
                sb.AppendLine($"        {v.Name} = {disc},");
                currentDisc = disc + 1;
            }
            sb.AppendLine("    }");
            sb.AppendLine();
            return;
        }

        // Tagged Union / Data Enum
        sb.AppendLine($"    public abstract partial record {enumName}");
        sb.AppendLine("    {");

        // Decode
        sb.AppendLine($"        internal static {enumName} Decode(WireReader reader) =>");
        sb.AppendLine("            reader.ReadU32() switch");
        sb.AppendLine("            {");
        long tagIndex = 0;
        foreach (var v in enumDecl.Variants)
        {
            long tag = v.Discriminant ?? tagIndex;
            tagIndex = tag + 1;
            if (v.PayloadFields.Count == 0)
            {
                sb.AppendLine($"                {tag} => new {v.Name}(),");
            }
            else
            {
                var readArgs = new List<string>();
                foreach (var f in v.PayloadFields)
                {
                    readArgs.Add(WireReadExpr(f.Type));
                }
                sb.AppendLine($"                {tag} => new {v.Name}({string.Join(", ", readArgs)}),");
            }
        }
        sb.AppendLine($"                uint tag => throw new global::System.InvalidOperationException($\"Invalid {enumName} tag: {{tag}}\")");
        sb.AppendLine("            };");
        sb.AppendLine();

        // Encode abstract method
        sb.AppendLine("        internal abstract void Encode(WireWriter writer);");
        sb.AppendLine();

        // Variant child records
        tagIndex = 0;
        foreach (var v in enumDecl.Variants)
        {
            long tag = v.Discriminant ?? tagIndex;
            tagIndex = tag + 1;

            if (v.PayloadFields.Count == 0)
            {
                sb.AppendLine($"        public sealed partial record {v.Name}() : {enumName}");
                sb.AppendLine("        {");
                sb.AppendLine($"            internal override void Encode(WireWriter writer) => writer.WriteU32({tag});");
                sb.AppendLine("        }");
            }
            else
            {
                var paramList = new List<string>();
                foreach (var f in v.PayloadFields)
                {
                    paramList.Add($"{MapType(f.Type)} {ToPascal(f.Name)}");
                }
                sb.AppendLine($"        public sealed partial record {v.Name}({string.Join(", ", paramList)}) : {enumName}");
                sb.AppendLine("        {");
                sb.AppendLine("            internal override void Encode(WireWriter writer)");
                sb.AppendLine("            {");
                sb.AppendLine($"                writer.WriteU32({tag});");
                foreach (var f in v.PayloadFields)
                {
                    sb.AppendLine($"                {WireWriteStatement(f.Type, ToPascal(f.Name))};");
                }
                sb.AppendLine("            }");
                sb.AppendLine("        }");
            }
            sb.AppendLine();
        }

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitClass(StringBuilder sb, BoltFfiClassDecl classDecl, Dictionary<string, Arbitration.MethodEmissionConfig>? methodConfigs = null)
    {
        string className = classDecl.Name.ToPascalCase();
        if (string.IsNullOrEmpty(className)) return;

        sb.AppendLine($"    public partial class {className} : IDisposable");
        sb.AppendLine("    {");
        sb.AppendLine("        private nint handle;");
        sb.AppendLine();
        sb.AppendLine("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        sb.AppendLine("        internal nint GetHandle()");
        sb.AppendLine("        {");
        sb.AppendLine("            nint h = handle;");
        sb.AppendLine("            if (h == 0) ThrowDisposed();");
        sb.AppendLine("            return h;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]");
        sb.AppendLine($"        private static void ThrowDisposed() => throw new global::System.ObjectDisposedException(nameof({className}));");
        sb.AppendLine();
        sb.AppendLine($"        internal {className}(nint handle, bool isHandle)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (handle == 0) throw new global::System.ArgumentException(\"handle must not be zero\", nameof(handle));");
        sb.AppendLine("            this.handle = handle;");
        sb.AppendLine("        }");
        sb.AppendLine();

        // 1. Initializers (Constructors)
        foreach (var init in classDecl.Initializers)
        {
            var initParams = new List<string>();
            var callArgs = new List<string>();
            bool hasComplexParam = false;
            foreach (var p in init.Parameters)
            {
                string pName = ToCamel(p.Name);
                initParams.Add($"{MapType(p.Type)} {pName}");
                if (p.Type.Kind == BoltFfiTypeKind.String || p.Type.Kind == BoltFfiTypeKind.Bytes || (p.Type.Kind == BoltFfiTypeKind.Record && !p.Type.IsDirectRecord))
                {
                    hasComplexParam = true;
                }
                else if (p.Type.Kind == BoltFfiTypeKind.Class)
                {
                    callArgs.Add($"{pName}.GetHandle()");
                }
                else
                {
                    callArgs.Add(pName);
                }
            }

            if (!hasComplexParam)
            {
                sb.AppendLine("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
                sb.AppendLine($"        public {className}({string.Join(", ", initParams)})");
                sb.AppendLine($"            : this(NativeMethods.{init.Symbol}({string.Join(", ", callArgs)}), true)");
                sb.AppendLine("        {");
                sb.AppendLine("        }");
                sb.AppendLine();
            }
            else
            {
                string helperName = $"__Create_{init.Symbol}";
                var helperArgs = new List<string>();
                foreach (var p in init.Parameters)
                {
                    helperArgs.Add(ToCamel(p.Name));
                }
                EmitMethod(sb, "        ", init, initParams, new List<string>(), helperName, "nint", isStatic: true, isAsync: false);
                sb.AppendLine("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
                sb.AppendLine($"        public {className}({string.Join(", ", initParams)})");
                sb.AppendLine($"            : this({helperName}({string.Join(", ", helperArgs)}), true)");
                sb.AppendLine("        {");
                sb.AppendLine("        }");
                sb.AppendLine();
            }
        }

        // 2. Instance Methods
        foreach (var m in classDecl.Methods)
        {
            string methodName = m.Name.ToPascalCase();
            string retType = MapType(m.ReturnType);
            var publicParams = new List<string>();
            foreach (var p in m.Parameters)
            {
                publicParams.Add($"{MapType(p.Type)} {ToCamel(p.Name)}");
            }

            bool isPartial = false;
            if (methodConfigs != null)
            {
                string qualifiedName = $"{className}.{methodName}";
                if (methodConfigs.TryGetValue(qualifiedName, out var cfg) ||
                    methodConfigs.TryGetValue(methodName, out cfg) ||
                    methodConfigs.TryGetValue(m.Name.ToSnakeCase(), out cfg))
                {
                    isPartial = cfg.IsPartial;
                }
            }

            EmitMethod(sb, "        ", m, publicParams, new List<string> { "GetHandle()" }, methodName, retType, isStatic: false, isAsync: m.IsAsync, isPartial: isPartial);
        }

        // 3. Dispose and Finalizer
        sb.AppendLine("        public void Dispose()");
        sb.AppendLine("        {");
        sb.AppendLine("            nint old = handle;");
        sb.AppendLine("            if (old != 0 && global::System.Threading.Interlocked.CompareExchange(ref handle, 0, old) == old)");
        sb.AppendLine("            {");
        if (!string.IsNullOrEmpty(classDecl.ReleaseSymbol))
        {
            sb.AppendLine($"                NativeMethods.{classDecl.ReleaseSymbol}(old);");
        }
        sb.AppendLine("            }");
        sb.AppendLine("            GC.SuppressFinalize(this);");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine($"        ~{className}() => Dispose();");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitCallback(StringBuilder sb, BoltFfiCallbackDecl callback)
    {
        string cbName = callback.Name.ToPascalCase();
        if (string.IsNullOrEmpty(cbName)) return;
        string ifaceName = $"I{cbName}";

        // Interface definition
        sb.AppendLine($"    public partial interface {ifaceName}");
        sb.AppendLine("    {");
        foreach (var m in callback.Methods)
        {
            string mName = m.Name.ToPascalCase();
            string retType = MapType(m.ReturnType);
            var mParams = new List<string>();
            foreach (var p in m.Parameters)
            {
                mParams.Add($"{MapType(p.Type)} {ToCamel(p.Name)}");
            }
            sb.AppendLine($"        {retType} {mName}({string.Join(", ", mParams)});");
        }
        sb.AppendLine("    }");
        sb.AppendLine();

        // Bridge class with thread-safe handle map
        string bridgeName = $"{cbName}Bridge";
        sb.AppendLine($"    internal static class {bridgeName}");
        sb.AppendLine("    {");
        sb.AppendLine($"        private static readonly global::System.Collections.Concurrent.ConcurrentDictionary<ulong, {ifaceName}> Handles = new();");
        sb.AppendLine("        private static long nextHandle = 1;");
        sb.AppendLine();
        sb.AppendLine($"        internal static ulong Register({ifaceName}? callback)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (callback == null) return 0;");
        sb.AppendLine("            ulong id = (ulong)global::System.Threading.Interlocked.Increment(ref nextHandle);");
        sb.AppendLine("            Handles[id] = callback;");
        sb.AppendLine("            return id;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine($"        internal static {ifaceName}? Get(ulong handle) =>");
        sb.AppendLine("            Handles.TryGetValue(handle, out var cb) ? cb : null;");
        sb.AppendLine();
        sb.AppendLine("        internal static void Free(ulong handle) =>");
        sb.AppendLine("            Handles.TryRemove(handle, out _);");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitNativeMethods(
        StringBuilder sb,
        List<BoltFfiDecl> decls,
        string libraryFileName)
    {
        string libStem = Path.GetFileNameWithoutExtension(libraryFileName);
        if (libStem.StartsWith("lib", StringComparison.OrdinalIgnoreCase))
        {
            libStem = libStem.Substring(3);
        }

        sb.AppendLine("    internal static partial class NativeMethods");
        sb.AppendLine("    {");
        sb.AppendLine($"        private const string NativeLib = \"{libStem}\";");
        sb.AppendLine();
        sb.AppendLine("        [SuppressGCTransition]");
        sb.AppendLine($"        [DllImport(NativeLib, EntryPoint = \"boltffi_free_buf\", CallingConvention = CallingConvention.Cdecl, ExactSpelling = true)]");
        sb.AppendLine("        internal static extern void boltffi_free_buf(FfiBuf buf);");
        sb.AppendLine();

        var emittedSymbols = new HashSet<string>(StringComparer.Ordinal);

        foreach (var decl in decls)
        {
            if (decl.Kind == BoltFfiDeclKind.Function && decl.Function != null)
            {
                EmitNativeFunction(sb, decl.Function, emittedSymbols);
            }
            else if (decl.Kind == BoltFfiDeclKind.Class && decl.Class != null)
            {
                // Initializers
                foreach (var init in decl.Class.Initializers)
                {
                    EmitNativeClassInitializer(sb, init, emittedSymbols);
                }

                // Instance Methods
                foreach (var m in decl.Class.Methods)
                {
                    EmitNativeClassMethod(sb, m, emittedSymbols);
                }

                // Release
                if (!string.IsNullOrEmpty(decl.Class.ReleaseSymbol) && emittedSymbols.Add(decl.Class.ReleaseSymbol))
                {
                    sb.AppendLine("        [SuppressGCTransition]");
                    sb.AppendLine($"        [DllImport(NativeLib, EntryPoint = \"{decl.Class.ReleaseSymbol}\", CallingConvention = CallingConvention.Cdecl, ExactSpelling = true)]");
                    sb.AppendLine($"        internal static extern void {decl.Class.ReleaseSymbol}(nint handle);");
                    sb.AppendLine();
                }
            }
        }

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitNativeFunction(
        StringBuilder sb,
        BoltFfiFunctionDecl func,
        HashSet<string> emittedSymbols)
    {
        if (string.IsNullOrEmpty(func.Symbol) || !emittedSymbols.Add(func.Symbol))
        {
            return;
        }

        string nativeRet = MapNativeType(func.ReturnType);
        var nativeParams = new List<string>();
        foreach (var p in func.Parameters)
        {
            if (p.Type.Kind == BoltFfiTypeKind.String || p.Type.Kind == BoltFfiTypeKind.Bytes || (p.Type.Kind == BoltFfiTypeKind.Record && !p.Type.IsDirectRecord))
            {
                nativeParams.Add($"nint {ToCamel(p.Name)}_ptr, nuint {ToCamel(p.Name)}_len");
            }
            else
            {
                nativeParams.Add($"{MapNativeType(p.Type)} {ToCamel(p.Name)}");
            }
        }

        if (func.HasError)
        {
            if (func.ReturnType.Kind != BoltFfiTypeKind.Void)
            {
                nativeParams.Add($"out {nativeRet} out_val");
            }
            nativeRet = "FfiBuf";
        }

        sb.AppendLine("        [SuppressGCTransition]");
        sb.AppendLine($"        [DllImport(NativeLib, EntryPoint = \"{func.Symbol}\", CallingConvention = CallingConvention.Cdecl, ExactSpelling = true)]");
        sb.AppendLine($"        internal static extern {nativeRet} {func.Symbol}({string.Join(", ", nativeParams)});");
        sb.AppendLine();
    }

