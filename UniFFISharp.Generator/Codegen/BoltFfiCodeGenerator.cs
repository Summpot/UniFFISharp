using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UniFFISharp.Generator.Metadata.BoltFfi;

namespace UniFFISharp.Generator.Codegen;

/// <summary>
/// Generates C# bindings for BoltFFI contracts.
/// Inlines lightweight runtime helpers (FfiBuf, WireReader, WireWriter)
/// and emits zero-copy blittable records and direct P/Invoke calls.
/// </summary>
public static class BoltFfiCodeGenerator
{
    public static string Generate(
        BoltFfiMetadataEnvelope envelope,
        string libraryFileName,
        string targetNamespace)
    {
        var native = envelope.Bindings.Native;
        if (native == null) return string.Empty;

        var sb = new StringBuilder();
        string cratePascal = envelope.Package.Name.ToPascalCase();
        if (string.IsNullOrEmpty(cratePascal)) cratePascal = "BoltModule";

        string crateSnake = envelope.Package.PackageName;
        if (string.IsNullOrEmpty(crateSnake)) crateSnake = cratePascal.ToLowerInvariant();

        // 1. Header
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// This file was generated by UniFFISharp (BoltFFI Engine). Do not edit.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CS0105");
        sb.AppendLine("#pragma warning disable CS8500");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Runtime.InteropServices;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine();

        // 2. Namespace
        string ns = string.IsNullOrWhiteSpace(targetNamespace) ? cratePascal : targetNamespace;
        sb.AppendLine($"namespace {ns}");
        sb.AppendLine("{");

        // 3. Inlined Lightweight Runtime
        EmitLightweightRuntime(sb);

        // 4. Data Types (Records, Enums, Classes)
        foreach (var decl in native.Decls)
        {
            if (decl.Kind == BoltFfiDeclKind.Record && decl.Record != null)
            {
                EmitRecord(sb, decl.Record);
            }
            else if (decl.Kind == BoltFfiDeclKind.Enum && decl.Enum != null)
            {
                EmitEnum(sb, decl.Enum);
            }
            else if (decl.Kind == BoltFfiDeclKind.Class && decl.Class != null)
            {
                EmitClass(sb, decl.Class, libraryFileName);
            }
        }

        // 5. Native Methods P/Invoke
        EmitNativeMethods(sb, native.Decls, libraryFileName, cratePascal);

        // 6. Public Friendly Methods Class
        EmitPublicMethods(sb, native.Decls, cratePascal);

        sb.AppendLine("}"); // end namespace

        return sb.ToString();
    }

    private static void EmitLightweightRuntime(StringBuilder sb)
    {
        sb.AppendLine("    #region Inlined BoltFFI Lightweight Runtime");
        sb.AppendLine();
        sb.AppendLine("    [StructLayout(LayoutKind.Sequential)]");
        sb.AppendLine("    internal struct FfiBuf");
        sb.AppendLine("    {");
        sb.AppendLine("        internal nint ptr;");
        sb.AppendLine("        internal nuint len;");
        sb.AppendLine("        internal nuint cap;");
        sb.AppendLine("        internal nuint align;");
        sb.AppendLine();
        sb.AppendLine("        internal static FfiBuf FromBytes(byte[]? bytes)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (bytes == null || bytes.Length == 0) return default;");
        sb.AppendLine("            nint mem = Marshal.AllocHGlobal(bytes.Length);");
        sb.AppendLine("            Marshal.Copy(bytes, 0, mem, bytes.Length);");
        sb.AppendLine("            return new FfiBuf { ptr = mem, len = (nuint)bytes.Length, cap = (nuint)bytes.Length, align = 1 };");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        internal static void Free(ref FfiBuf buf)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (buf.ptr != 0)");
        sb.AppendLine("            {");
        sb.AppendLine("                Marshal.FreeHGlobal(buf.ptr);");
        sb.AppendLine("                buf = default;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        internal byte[] ToArray()");
        sb.AppendLine("        {");
        sb.AppendLine("            if (ptr == 0 || len == 0) return Array.Empty<byte>();");
        sb.AppendLine("            int byteLen = checked((int)len);");
        sb.AppendLine("            byte[] arr = new byte[byteLen];");
        sb.AppendLine("            Marshal.Copy(ptr, arr, 0, byteLen);");
        sb.AppendLine("            return arr;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        internal string ReadString()");
        sb.AppendLine("        {");
        sb.AppendLine("            if (ptr == 0 || len == 0) return string.Empty;");
        sb.AppendLine("            return global::System.Text.Encoding.UTF8.GetString(ToArray());");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    [StructLayout(LayoutKind.Sequential)]");
        sb.AppendLine("    internal struct BoltFfiStatus");
        sb.AppendLine("    {");
        sb.AppendLine("        internal int code;");
        sb.AppendLine("        internal FfiBuf error;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    internal sealed class WireReader");
        sb.AppendLine("    {");
        sb.AppendLine("        private readonly nint pointer;");
        sb.AppendLine("        private readonly int length;");
        sb.AppendLine("        private int position;");
        sb.AppendLine();
        sb.AppendLine("        internal WireReader(FfiBuf buffer) : this(buffer.ptr, buffer.len) { }");
        sb.AppendLine("        internal WireReader(nint pointer, nuint length)");
        sb.AppendLine("        {");
        sb.AppendLine("            this.pointer = pointer;");
        sb.AppendLine("            this.length = pointer == 0 ? 0 : checked((int)length);");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        internal bool ReadBool() => ReadU8() != 0;");
        sb.AppendLine("        internal sbyte ReadI8() => (sbyte)ReadU8();");
        sb.AppendLine("        internal byte ReadU8()");
        sb.AppendLine("        {");
        sb.AppendLine("            if (position >= length) throw new System.IO.EndOfStreamException();");
        sb.AppendLine("            byte b = Marshal.ReadByte(pointer, position);");
        sb.AppendLine("            position++;");
        sb.AppendLine("            return b;");
        sb.AppendLine("        }");
        sb.AppendLine("        internal short ReadI16()");
        sb.AppendLine("        {");
        sb.AppendLine("            short val = Marshal.ReadInt16(pointer, position);");
        sb.AppendLine("            position += 2;");
        sb.AppendLine("            return val;");
        sb.AppendLine("        }");
        sb.AppendLine("        internal ushort ReadU16() => (ushort)ReadI16();");
        sb.AppendLine("        internal int ReadI32()");
        sb.AppendLine("        {");
        sb.AppendLine("            int val = Marshal.ReadInt32(pointer, position);");
        sb.AppendLine("            position += 4;");
        sb.AppendLine("            return val;");
        sb.AppendLine("        }");
        sb.AppendLine("        internal uint ReadU32() => (uint)ReadI32();");
        sb.AppendLine("        internal long ReadI64()");
        sb.AppendLine("        {");
        sb.AppendLine("            long val = Marshal.ReadInt64(pointer, position);");
        sb.AppendLine("            position += 8;");
        sb.AppendLine("            return val;");
        sb.AppendLine("        }");
        sb.AppendLine("        internal ulong ReadU64() => (ulong)ReadI64();");
        sb.AppendLine("        internal float ReadF32()");
        sb.AppendLine("        {");
        sb.AppendLine("            int bits = ReadI32();");
        sb.AppendLine("            return BitConverter.Int32BitsToSingle(bits);");
        sb.AppendLine("        }");
        sb.AppendLine("        internal double ReadF64()");
        sb.AppendLine("        {");
        sb.AppendLine("            long bits = ReadI64();");
        sb.AppendLine("            return BitConverter.Int64BitsToDouble(bits);");
        sb.AppendLine("        }");
        sb.AppendLine("        internal string ReadString()");
        sb.AppendLine("        {");
        sb.AppendLine("            int strLen = checked((int)ReadU64());");
        sb.AppendLine("            if (strLen == 0) return string.Empty;");
        sb.AppendLine("            byte[] bytes = new byte[strLen];");
        sb.AppendLine("            Marshal.Copy(pointer + position, bytes, 0, strLen);");
        sb.AppendLine("            position += strLen;");
        sb.AppendLine("            return Encoding.UTF8.GetString(bytes);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    internal sealed class WireWriter");
        sb.AppendLine("    {");
        sb.AppendLine("        private readonly System.IO.MemoryStream stream = new();");
        sb.AppendLine();
        sb.AppendLine("        internal void WriteBool(bool val) => stream.WriteByte(val ? (byte)1 : (byte)0);");
        sb.AppendLine("        internal void WriteI8(sbyte val) => stream.WriteByte((byte)val);");
        sb.AppendLine("        internal void WriteU8(byte val) => stream.WriteByte(val);");
        sb.AppendLine("        internal void WriteI16(short val)");
        sb.AppendLine("        {");
        sb.AppendLine("            stream.WriteByte((byte)(val & 0xFF));");
        sb.AppendLine("            stream.WriteByte((byte)((val >> 8) & 0xFF));");
        sb.AppendLine("        }");
        sb.AppendLine("        internal void WriteU16(ushort val) => WriteI16((short)val);");
        sb.AppendLine("        internal void WriteI32(int val)");
        sb.AppendLine("        {");
        sb.AppendLine("            for (int i = 0; i < 4; i++) { stream.WriteByte((byte)(val & 0xFF)); val >>= 8; }");
        sb.AppendLine("        }");
        sb.AppendLine("        internal void WriteU32(uint val) => WriteI32((int)val);");
        sb.AppendLine("        internal void WriteI64(long val)");
        sb.AppendLine("        {");
        sb.AppendLine("            for (int i = 0; i < 8; i++) { stream.WriteByte((byte)(val & 0xFF)); val >>= 8; }");
        sb.AppendLine("        }");
        sb.AppendLine("        internal void WriteU64(ulong val) => WriteI64((long)val);");
        sb.AppendLine("        internal void WriteF32(float val) => WriteI32(BitConverter.SingleToInt32Bits(val));");
        sb.AppendLine("        internal void WriteF64(double val) => WriteI64(BitConverter.DoubleToInt64Bits(val));");
        sb.AppendLine("        internal void WriteString(string? str)");
        sb.AppendLine("        {");
        sb.AppendLine("            byte[] bytes = Encoding.UTF8.GetBytes(str ?? string.Empty);");
        sb.AppendLine("            WriteU64((ulong)bytes.Length);");
        sb.AppendLine("            if (bytes.Length > 0) stream.Write(bytes, 0, bytes.Length);");
        sb.AppendLine("        }");
        sb.AppendLine("        internal byte[] ToArray() => stream.ToArray();");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    #endregion");
        sb.AppendLine();
    }

    private static void EmitRecord(StringBuilder sb, BoltFfiRecordDecl record)
    {
        string recordName = record.Name.ToPascalCase();
        if (string.IsNullOrEmpty(recordName)) return;

        if (record.IsDirect)
        {
            sb.AppendLine("    [StructLayout(LayoutKind.Sequential)]");
            sb.AppendLine($"    public partial struct {recordName} : IEquatable<{recordName}>");
            sb.AppendLine("    {");

            foreach (var f in record.Fields)
            {
                string fName = ToPascal(f.Name);
                string fType = MapType(f.Type);
                sb.AppendLine($"        public {fType} {fName};");
            }

            // Constructor
            if (record.Fields.Count > 0)
            {
                sb.AppendLine();
                var paramList = new List<string>();
                foreach (var f in record.Fields)
                {
                    paramList.Add($"{MapType(f.Type)} {ToCamel(f.Name)}");
                }
                sb.AppendLine($"        public {recordName}({string.Join(", ", paramList)})");
                sb.AppendLine("        {");
                foreach (var f in record.Fields)
                {
                    sb.AppendLine($"            this.{ToPascal(f.Name)} = {ToCamel(f.Name)};");
                }
                sb.AppendLine("        }");
            }

            // Equality
            sb.AppendLine();
            sb.AppendLine($"        public bool Equals({recordName} other) =>");
            if (record.Fields.Count == 0)
            {
                sb.AppendLine("            true;");
            }
            else
            {
                var eqParts = new List<string>();
                foreach (var f in record.Fields)
                {
                    string fName = ToPascal(f.Name);
                    eqParts.Add($"EqualityComparer<{MapType(f.Type)}>.Default.Equals({fName}, other.{fName})");
                }
                sb.AppendLine($"            {string.Join(" &&\n            ", eqParts)};");
            }
            sb.AppendLine($"        public override bool Equals(object? obj) => obj is {recordName} other && Equals(other);");
            sb.AppendLine("        public override int GetHashCode()");
            sb.AppendLine("        {");
            if (record.Fields.Count == 0)
            {
                sb.AppendLine("            return 0;");
            }
            else
            {
                sb.AppendLine("            var hash = new HashCode();");
                foreach (var f in record.Fields)
                {
                    sb.AppendLine($"            hash.Add({ToPascal(f.Name)});");
                }
                sb.AppendLine("            return hash.ToHashCode();");
            }
            sb.AppendLine("        }");
            sb.AppendLine($"        public static bool operator ==({recordName} left, {recordName} right) => left.Equals(right);");
            sb.AppendLine($"        public static bool operator !=({recordName} left, {recordName} right) => !left.Equals(right);");

            sb.AppendLine("    }");
        }
        else
        {
            // Encoded record
            sb.AppendLine($"    public partial record struct {recordName}");
            sb.AppendLine("    {");
            foreach (var f in record.Fields)
            {
                string fName = ToPascal(f.Name);
                string fType = MapType(f.Type);
                sb.AppendLine($"        public {fType} {fName} {{ get; set; }}");
            }

            if (record.Fields.Count > 0)
            {
                sb.AppendLine();
                var paramList = new List<string>();
                foreach (var f in record.Fields)
                {
                    paramList.Add($"{MapType(f.Type)} {ToCamel(f.Name)}");
                }
                sb.AppendLine($"        public {recordName}({string.Join(", ", paramList)})");
                sb.AppendLine("        {");
                foreach (var f in record.Fields)
                {
                    sb.AppendLine($"            this.{ToPascal(f.Name)} = {ToCamel(f.Name)};");
                }
                sb.AppendLine("        }");
            }
            sb.AppendLine("    }");
        }
        sb.AppendLine();
    }

    private static void EmitEnum(StringBuilder sb, BoltFfiEnumDecl enumDecl)
    {
        string enumName = enumDecl.Name.ToPascalCase();
        if (string.IsNullOrEmpty(enumName)) return;

        sb.AppendLine($"    public enum {enumName}");
        sb.AppendLine("    {");
        long currentDisc = 0;
        foreach (var v in enumDecl.Variants)
        {
            long disc = v.Discriminant ?? currentDisc;
            sb.AppendLine($"        {v.Name} = {disc},");
            currentDisc = disc + 1;
        }
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitClass(StringBuilder sb, BoltFfiClassDecl classDecl, string libraryFileName)
    {
        string className = classDecl.Name.ToPascalCase();
        if (string.IsNullOrEmpty(className)) return;

        sb.AppendLine($"    public partial class {className} : IDisposable");
        sb.AppendLine("    {");
        sb.AppendLine("        private nint handle;");
        sb.AppendLine();
        sb.AppendLine($"        internal {className}(nint handle)");
        sb.AppendLine("        {");
        sb.AppendLine("            this.handle = handle;");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        internal nint GetHandle() => handle;");
        sb.AppendLine();
        sb.AppendLine("        public void Dispose()");
        sb.AppendLine("        {");
        sb.AppendLine("            if (handle != 0)");
        sb.AppendLine("            {");
        if (!string.IsNullOrEmpty(classDecl.ReleaseSymbol))
        {
            sb.AppendLine($"                NativeMethods.{classDecl.ReleaseSymbol}(handle);");
        }
        sb.AppendLine("                handle = 0;");
        sb.AppendLine("            }");
        sb.AppendLine("            GC.SuppressFinalize(this);");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine($"        ~{className}() => Dispose();");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitNativeMethods(
        StringBuilder sb,
        List<BoltFfiDecl> decls,
        string libraryFileName,
        string cratePascal)
    {
        string libStem = Path.GetFileNameWithoutExtension(libraryFileName);
        if (libStem.StartsWith("lib", StringComparison.OrdinalIgnoreCase))
        {
            libStem = libStem.Substring(3);
        }

        sb.AppendLine("    internal static partial class NativeMethods");
        sb.AppendLine("    {");
        sb.AppendLine($"        private const string NativeLib = \"{libStem}\";");
        sb.AppendLine();

        var emittedSymbols = new HashSet<string>(StringComparer.Ordinal);

        foreach (var decl in decls)
        {
            if (decl.Kind == BoltFfiDeclKind.Function && decl.Function != null)
            {
                EmitNativeFunction(sb, decl.Function, emittedSymbols);
            }
            else if (decl.Kind == BoltFfiDeclKind.Class && decl.Class != null && !string.IsNullOrEmpty(decl.Class.ReleaseSymbol))
            {
                if (emittedSymbols.Add(decl.Class.ReleaseSymbol))
                {
                    sb.AppendLine($"        [DllImport(NativeLib, EntryPoint = \"{decl.Class.ReleaseSymbol}\", CallingConvention = CallingConvention.Cdecl)]");
                    sb.AppendLine($"        internal static extern void {decl.Class.ReleaseSymbol}(nint handle);");
                    sb.AppendLine();
                }
            }
        }

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitNativeFunction(
        StringBuilder sb,
        BoltFfiFunctionDecl func,
        HashSet<string> emittedSymbols)
    {
        if (string.IsNullOrEmpty(func.Symbol) || !emittedSymbols.Add(func.Symbol))
        {
            return;
        }

        string nativeRet = MapNativeType(func.ReturnType);
        var nativeParams = new List<string>();
        foreach (var p in func.Parameters)
        {
            nativeParams.Add($"{MapNativeType(p.Type)} {ToCamel(p.Name)}");
        }

        sb.AppendLine($"        [DllImport(NativeLib, EntryPoint = \"{func.Symbol}\", CallingConvention = CallingConvention.Cdecl)]");
        sb.AppendLine($"        internal static extern {nativeRet} {func.Symbol}({string.Join(", ", nativeParams)});");
        sb.AppendLine();
    }

    private static void EmitPublicMethods(
        StringBuilder sb,
        List<BoltFfiDecl> decls,
        string cratePascal)
    {
        sb.AppendLine($"    public static partial class {cratePascal}Methods");
        sb.AppendLine("    {");

        foreach (var decl in decls)
        {
            if (decl.Kind == BoltFfiDeclKind.Function && decl.Function != null)
            {
                var func = decl.Function;
                string methodName = func.Name.ToPascalCase();
                string retType = MapType(func.ReturnType);
                var publicParams = new List<string>();
                var callArgs = new List<string>();

                foreach (var p in func.Parameters)
                {
                    string pName = ToCamel(p.Name);
                    publicParams.Add($"{MapType(p.Type)} {pName}");
                    if (p.Type.Kind == BoltFfiTypeKind.Class)
                    {
                        callArgs.Add($"{pName}.GetHandle()");
                    }
                    else if (p.Type.Kind == BoltFfiTypeKind.String)
                    {
                        callArgs.Add($"FfiBuf.FromBytes(global::System.Text.Encoding.UTF8.GetBytes({pName} ?? string.Empty))");
                    }
                    else if (p.Type.Kind == BoltFfiTypeKind.Bytes)
                    {
                        callArgs.Add($"FfiBuf.FromBytes({pName})");
                    }
                    else
                    {
                        callArgs.Add(pName);
                    }
                }

                string callExpr = $"NativeMethods.{func.Symbol}({string.Join(", ", callArgs)})";
                string returnExpr = callExpr;
                if (func.ReturnType.Kind == BoltFfiTypeKind.Class)
                {
                    string clsName = !string.IsNullOrEmpty(func.ReturnType.CustomTypeName)
                        ? ToPascal(func.ReturnType.CustomTypeName)
                        : "object";
                    returnExpr = $"new {clsName}({callExpr})";
                }
                else if (func.ReturnType.Kind == BoltFfiTypeKind.String)
                {
                    returnExpr = $"{callExpr}.ReadString()";
                }
                else if (func.ReturnType.Kind == BoltFfiTypeKind.Bytes)
                {
                    returnExpr = $"{callExpr}.ToArray()";
                }

                if (func.IsAsync)
                {
                    string taskRet = (retType == "void") ? "Task" : $"Task<{retType}>";
                    sb.AppendLine($"        public static async {taskRet} {methodName}({string.Join(", ", publicParams)})");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            await Task.Yield();");
                    if (retType == "void")
                    {
                        sb.AppendLine($"            {callExpr};");
                    }
                    else
                    {
                        sb.AppendLine($"            return {returnExpr};");
                    }
                    sb.AppendLine("        }");
                }
                else
                {
                    sb.AppendLine($"        public static {retType} {methodName}({string.Join(", ", publicParams)})");
                    sb.AppendLine("        {");
                    if (retType == "void")
                    {
                        sb.AppendLine($"            {callExpr};");
                    }
                    else
                    {
                        sb.AppendLine($"            return {returnExpr};");
                    }
                    sb.AppendLine("        }");
                }
                sb.AppendLine();
            }
        }

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static string MapType(BoltFfiType ty)
    {
        return ty.Kind switch
        {
            BoltFfiTypeKind.Void => "void",
            BoltFfiTypeKind.Bool => "bool",
            BoltFfiTypeKind.Int8 => "sbyte",
            BoltFfiTypeKind.UInt8 => "byte",
            BoltFfiTypeKind.Int16 => "short",
            BoltFfiTypeKind.UInt16 => "ushort",
            BoltFfiTypeKind.Int32 => "int",
            BoltFfiTypeKind.UInt32 => "uint",
            BoltFfiTypeKind.Int64 => "long",
            BoltFfiTypeKind.UInt64 => "ulong",
            BoltFfiTypeKind.Float32 => "float",
            BoltFfiTypeKind.Float64 => "double",
            BoltFfiTypeKind.String => "string",
            BoltFfiTypeKind.Bytes => "byte[]",
            BoltFfiTypeKind.Record => !string.IsNullOrEmpty(ty.CustomTypeName) ? ty.CustomTypeName : "object",
            BoltFfiTypeKind.Enum => !string.IsNullOrEmpty(ty.CustomTypeName) ? ty.CustomTypeName : "int",
            BoltFfiTypeKind.Class => !string.IsNullOrEmpty(ty.CustomTypeName) ? ty.CustomTypeName : "object",
            BoltFfiTypeKind.Option => $"{MapType(ty.InnerType ?? BoltFfiType.Void)}?",
            BoltFfiTypeKind.Sequence => $"System.Collections.Generic.List<{MapType(ty.InnerType ?? BoltFfiType.Void)}>",
            _ => "object"
        };
    }

    private static string MapNativeType(BoltFfiType ty)
    {
        return ty.Kind switch
        {
            BoltFfiTypeKind.String or BoltFfiTypeKind.Bytes => "FfiBuf",
            BoltFfiTypeKind.Class => "nint",
            _ => MapType(ty)
        };
    }

    private static string ToPascal(string name)
    {
        if (string.IsNullOrEmpty(name)) return string.Empty;
        var parts = name.Split(new[] { '_' }, StringSplitOptions.RemoveEmptyEntries);
        var sb = new StringBuilder();
        foreach (var p in parts)
        {
            sb.Append(char.ToUpperInvariant(p[0]));
            if (p.Length > 1) sb.Append(p.Substring(1));
        }
        return sb.ToString();
    }

    private static string ToCamel(string name)
    {
        string pascal = ToPascal(name);
        if (string.IsNullOrEmpty(pascal)) return string.Empty;
        return char.ToLowerInvariant(pascal[0]) + (pascal.Length > 1 ? pascal.Substring(1) : string.Empty);
    }
}
